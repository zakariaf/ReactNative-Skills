// src/core/game/levels.ts
// The level side of a game module: shipped levels, packs, the solver and the daily and endless
// modes. level-generation-and-solvers fills it in; the generator is GameEngine.create(seed, difficulty).
import type { MessageId } from '@/core/game/messages';

/**
 * Puzzle games rate against par, score games against thresholds [win, two, three]:
 * thresholds[0] is the lowest score a win can have (0 when the win is not score-based); two and
 * three stars need thresholds[1] and thresholds[2].
 */
export type StarRule =
  | { readonly kind: 'par'; readonly par: number }
  | { readonly kind: 'score'; readonly thresholds: readonly [number, number, number] };

/** One shipped level: generated by tooling, solver-checked, committed as JSON. */
export type LevelEntry = {
  /** 1-based and global across packs ("Level 12"). */
  readonly level: number;
  readonly seed: number;
  readonly difficulty: number;
  readonly stars: StarRule;
};

/** Packs unlock by stars collected. */
export type LevelPack = {
  readonly id: string;
  readonly nameId: MessageId;
  readonly firstLevel: number;
  readonly levelCount: number;
  readonly starsToUnlock: number;
};

/**
 * A solver's answer. `solved` carries the winning line, its length (par for an exact solver) and
 * the state the line ends in, so a score-rated plan reads the score without a replay.
 * `unsolvable` means the whole space was searched; `budget-exceeded` only that the solver gave up.
 */
export type SolveResult<TState, TMove> =
  | {
      readonly kind: 'solved';
      readonly par: number;
      readonly line: readonly TMove[];
      readonly final: TState;
    }
  | { readonly kind: 'unsolvable' }
  | { readonly kind: 'budget-exceeded' };

/**
 * Proves a level winnable: an exact search (par) or, for games that draw their future from the
 * RNG, a witness line. Tooling and tests only, never at runtime.
 */
export type Solver<TState, TMove> = {
  readonly solve: (start: TState, maxNodes: number) => SolveResult<TState, TMove>;
};

export type LevelsSpec<TState, TMove> = {
  /** Difficulty curve 0..99 by level; tooling regenerates the level tables from it. */
  readonly difficultyFor: (level: number) => number;
  readonly packs: readonly LevelPack[];
  /** The shipped level tables, concatenated; one entry per level. */
  readonly table: readonly LevelEntry[];
  readonly solver: Solver<TState, TMove> | null;
  readonly daily:
    | { readonly kind: 'none' }
    | { readonly kind: 'daily'; readonly difficulty: number; readonly salt: number };
  /** { kind: 'endless', difficulty: ENDLESS_DIFFICULTY } when the game has an endless mode. */
  readonly endless:
    { readonly kind: 'none' } | { readonly kind: 'endless'; readonly difficulty: number };
};
