/** Validate tools/catalog.json; structural errors are bad input (exit 2). */
export function readCatalog(path) {
  const catalog = readJson(path, `catalog ${path}`);
  if (!Array.isArray(catalog.categories) || !Array.isArray(catalog.skills)) throw new UsageError(`catalog ${path} needs "categories" and "skills" arrays`, 'Restore tools/catalog.json.');
  return catalog;
}

/** The description split into its lead (what it does), the "Use when" clause and the "Not for" clause. */
export function splitDescription(description, std) {
  const trigger = std.description.triggerPhrase;
  const notFor = std.description.notForPhrase;
  const at = description.indexOf(trigger);
  const lead = (at === -1 ? description : description.slice(0, at)).trim();
  const rest = at === -1 ? '' : description.slice(at + trigger.length).trim();
  const notAt = rest.indexOf(notFor);
  return { lead, useWhen: (notAt === -1 ? rest : rest.slice(0, notAt)).trim().replace(/[.;,\s]+$/, ''), notFor: notAt === -1 ? '' : rest.slice(notAt).trim() };
}

/** Read every skill's frontmatter and join it with the catalogue. Returns { skills, problems, notes, planned, categories }. */
export function buildModel({ catalog, skillsRoot, std }) {
  const problems = [];
  const notes = [];
  const categories = new Map(catalog.categories.map((category) => [category.key, category.label]));
  const pluginByKey = new Map(PLUGINS.map((plugin) => [plugin.key, plugin]));
  const entries = new Map();
  for (const item of catalog.skills) {
    if (entries.has(item.name)) problems.push({ file: 'tools/catalog.json', rule: 'catalog-data', message: `skill ${item.name} is listed twice`, fix: 'Keep one entry.' });
    if (!categories.has(item.category)) problems.push({ file: 'tools/catalog.json', rule: 'catalog-data', message: `skill ${item.name} has the unknown category "${item.category}"`, fix: `Use one of: ${[...categories.keys()].join(', ')}.` });
    if (!pluginByKey.has(item.plugin)) problems.push({ file: 'tools/catalog.json', rule: 'catalog-data', message: `skill ${item.name} has the unknown plugin "${item.plugin}"`, fix: `Use one of: ${[...pluginByKey.keys()].join(', ')}.` });
    entries.set(item.name, item);
  }
  const onDisk = new Map(listSkillDirs(skillsRoot).map((target) => [target.name, target]));
  const runbookKey = std.frontmatter.runbook.key;
  const skills = [];
  for (const item of catalog.skills) {
    const target = onDisk.get(item.name);
    if (!target) continue;
    const skillMd = join(target.dir, 'SKILL.md');
    if (!existsSync(skillMd)) {
      problems.push({ file: `skills/${item.name}`, rule: 'skill-frontmatter', message: 'has no SKILL.md, so it is left out of the catalogue', fix: 'Add SKILL.md or remove the folder.' });
      continue;
    }
    const fm = splitFrontmatter(readFileSync(skillMd, 'utf8'));
    const { data } = fm.closed ? parseYamlSubset(fm.yaml) : { data: {} };
    if (typeof data.description !== 'string' || data.description.trim() === '') {
      problems.push({ file: `skills/${item.name}/SKILL.md`, rule: 'skill-frontmatter', message: 'has no readable one-line description, so it is left out of the catalogue', fix: 'Fix the frontmatter (node tools/validate-skills.mjs names the problem).' });
      continue;
    }
    // validate-skills owns name-match; the catalogue keys on the folder name, so this is only a note here.
    if (data.name !== item.name) notes.push(`note: skills/${item.name}/SKILL.md says name ${JSON.stringify(data.name)}; the catalogue uses the folder name (validate-skills reports name-match)`);
    const flagged = String(data[runbookKey]) === String(std.frontmatter.runbook.value);
    if (Boolean(item.manual) !== flagged) problems.push({ file: `skills/${item.name}/SKILL.md`, rule: 'manual-mismatch', message: `catalog.json says manual: ${Boolean(item.manual)} but the frontmatter ${flagged ? 'sets' : 'does not set'} ${runbookKey}`, fix: 'Make catalog.json "manual" and the frontmatter flag agree (manual runbooks are run-* skills).' });
    const rich = ['references', 'templates', 'scripts'].some((folder) => existsSync(join(target.dir, folder)));
    skills.push({
      name: item.name,
      description: data.description.trim(),
      category: item.category,
      categoryLabel: categories.get(item.category) ?? item.category,
      plugin: pluginByKey.get(item.plugin)?.name ?? item.plugin,
      manual: Boolean(item.manual) || flagged,
      rich,
      checker: existsSync(join(target.dir, 'scripts', 'selftest.mjs')),
      path: `skills/${item.name}`,
    });
  }
  for (const name of [...onDisk.keys()].filter((key) => !entries.has(key))) {
    problems.push({ file: `skills/${name}`, rule: 'skill-uncatalogued', message: 'is on disk but not in tools/catalog.json, so it has no category or plugin', fix: 'Add it to tools/catalog.json (name, category, plugin, manual) or remove the folder.' });
  }
  const planned = catalog.skills.filter((item) => !onDisk.has(item.name)).map((item) => item.name);
  return { skills, problems, notes, planned, categories: catalog.categories };
}

