// frontmatter: skills.json, docs/skills-data.js, the two plugin entries in .claude-plugin/marketplace.json,
// the skill tables in README.md and the intent map in AGENTS.md (between generated markers).
// With --check it writes nothing and fails when any of them is stale.
// Usage: node tools/build-catalog.mjs [--check] [options]   (see --help)

