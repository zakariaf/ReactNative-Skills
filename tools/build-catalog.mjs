const cell = (text) => text.replace(/\|/g, '\\|').replace(/\s+/g, ' ').trim();
const sentence = (text) => (/[.!?]$/.test(text) ? text : `${text}.`);

export function renderSkillsJson(model) {
  const data = {
    name: 'React Native Agent Skills',
    repo: REPO_SLUG,
    standard: 'https://agentskills.io',
    count: model.skills.length,
    planned: model.skills.length + model.planned.length,
    categories: model.categories.map(({ key, label }) => ({ key, label })),
    plugins: PLUGINS.map((plugin) => ({ name: plugin.name, key: plugin.key, count: model.skills.filter((skill) => skill.plugin === plugin.name).length })),
    skills: model.skills,
  };
  return `${JSON.stringify(data, null, 2)}\n`;
}

export function renderSkillsDataJs(model) {
  return [
    `// ${GENERATED_NOTE}`,
    `window.SKILL_CATEGORIES = ${JSON.stringify(model.categories.map(({ key, label }) => ({ key, label })), null, 2)};`,
    `window.SKILLS = ${JSON.stringify(model.skills, null, 2)};`,
    '',
  ].join('\n');
}

export function renderReadmeBlock(model, std) {
  const lines = [MARKERS.skills.start, `<!-- ${GENERATED_NOTE} -->`, ''];
  const counts = PLUGINS.map((plugin) => `\`${plugin.name}\` ${model.skills.filter((skill) => skill.plugin === plugin.name).length}`).join(' · ');
  lines.push(`**${model.skills.length} skills** (${counts})${model.planned.length ? ` · ${model.planned.length} more planned` : ''}`, '');
  for (const category of model.categories) {
    const skills = model.skills.filter((skill) => skill.category === category.key);
    if (skills.length === 0) continue;
    lines.push(`### ${category.label}`, '', '| Skill | What it does |', '|---|---|');
    for (const skill of skills) {
      const { lead } = splitDescription(skill.description, std);
      const tags = [skill.manual ? 'runbook, invoked by name' : '', skill.plugin !== PLUGINS[0].name ? `plugin \`${skill.plugin}\`` : ''].filter(Boolean);
      lines.push(`| [\`${skill.name}\`](${skill.path}/SKILL.md) | ${cell(sentence(lead))}${tags.length ? ` *(${tags.join('; ')})*` : ''} |`);
    }
    lines.push('');
  }
  lines.push(MARKERS.skills.end);
  return lines.join('\n');
}

export function renderIntentsBlock(model, std) {
  const lines = [MARKERS.intents.start, `<!-- ${GENERATED_NOTE} -->`, ''];
  for (const category of model.categories) {
    const skills = model.skills.filter((skill) => skill.category === category.key);
    if (skills.length === 0) continue;
    lines.push(`### ${category.label}`, '');
    for (const skill of skills) {
      const { lead, useWhen } = splitDescription(skill.description, std);
      const when = useWhen ? `${std.description.triggerPhrase.toLowerCase()} ${useWhen}` : lead.replace(/[.\s]+$/, '');
      lines.push(`- \`${skill.name}\`${skill.manual ? ' (runbook: only when asked by name)' : ''}: ${cell(when)}.`);
    }
    lines.push('');
  }
  lines.push(MARKERS.intents.end);
  return lines.join('\n');
}

/** The marketplace with the two plugin entries updated (other fields and entries kept as they are). */
export function renderMarketplace(existingText, model) {
  let data;
  if (existingText) {
    try {
      data = JSON.parse(existingText);
    } catch (error) {
      throw new UsageError(`.claude-plugin/marketplace.json is not valid JSON: ${error.message}`, 'Fix the JSON or delete the file so build-catalog writes a fresh one.');
    }
  } else {
    data = {
      name: 'react-native-skills',
      owner: { name: 'Zakaria Fatahi' },
      metadata: { description: 'Deep, self-verifying React Native and Expo engineering skills for Claude Code and other agents.' },
      plugins: [],
    };
  }
  if (!Array.isArray(data.plugins)) data.plugins = [];
  for (const plugin of PLUGINS) {
    const skills = model.skills.filter((skill) => skill.plugin === plugin.name).map((skill) => `./${skill.path}`);
    let entry = data.plugins.find((item) => item?.name === plugin.name);
    if (!entry) {
      entry = { name: plugin.name };
      data.plugins.push(entry);
    }
    // Generated fields are authoritative; any other field of the entry (category, tags, ...) is kept.
    Object.assign(entry, { source: './', description: plugin.description, ...PLUGIN_META, keywords: plugin.keywords, skills });
  }
  return `${JSON.stringify(data, null, 2)}\n`;
}

/** Replace the text between a marker pair; returns null when the markers are missing. */
export function replaceBlock(text, markers, block) {
  const start = text.indexOf(markers.start);
  const end = text.indexOf(markers.end);
  if (start === -1 || end === -1 || end < start) return null;
  return `${text.slice(0, start)}${block}${text.slice(end + markers.end.length)}`;
}

