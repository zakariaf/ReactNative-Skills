const SPEC = {
  name: 'build-catalog',
  summary: 'Writes skills.json, docs/skills-data.js, the react-native and react-native-games entries of .claude-plugin/marketplace.json, the skill tables in README.md and the intent map in AGENTS.md from tools/catalog.json and each skill\'s frontmatter. With --check it writes nothing and fails on any stale file.',
  usage: '[--check] [options]',
  options: {
    check: { type: 'boolean', help: 'Change nothing; exit 1 when a generated file is missing or stale' },
    repo: { type: 'string', value: 'dir', help: 'Repository the generated files live in (default: the repo that holds tools/)' },
    'skills-root': { type: 'string', value: 'dir', help: 'Folder that holds the skill folders (default: <repo>/skills)' },
    catalog: { type: 'string', value: 'file', help: 'Catalogue (default: <repo>/tools/catalog.json, else this repo\'s)' },
    standard: { type: 'string', value: 'file', help: 'Standard constants file (default: tools/standard.json)' },
  },
  positionals: { min: 0, max: 0 },
  details: [
    'Generated blocks: README.md between <!-- generated:skills:start --> and <!-- generated:skills:end -->,',
    'AGENTS.md between <!-- generated:intents:start --> and <!-- generated:intents:end -->. A missing README.md or',
    'AGENTS.md is created as a placeholder holding the markers; a file without markers gets them appended.',
    'Skills listed in catalog.json but not on disk yet are reported as planned (not a problem). A skill folder',
    'missing from catalog.json, a frontmatter that cannot be read, and a "manual" flag that disagrees with the',
    'frontmatter are problems. .claude-plugin/plugin.json must not exist: both entries use "source": "./", so it',
    'would name both plugins (one namespace for all skills); each entry carries its own metadata and a "skills"',
    'list that replaces the default skills/ scan.',
  ].join('\n'),
};

async function main() {
  const { options } = parseArgs(process.argv.slice(2), SPEC);
  const repo = resolve(options.repo ?? REPO_ROOT);
  if (!existsSync(repo)) throw new UsageError(`repo ${repo} does not exist`, 'Pass --repo <dir>.');
  const skillsRoot = resolve(options['skills-root'] ?? join(repo, 'skills'));
  if (!existsSync(skillsRoot)) throw new UsageError(`skills root ${skillsRoot} does not exist`, 'Pass --skills-root <dir>.');
  const catalogPath = resolve(options.catalog ?? (existsSync(join(repo, 'tools', 'catalog.json')) ? join(repo, 'tools', 'catalog.json') : join(REPO_ROOT, 'tools', 'catalog.json')));
  const std = loadStandard(options.standard ?? STANDARD_PATH);
  const model = buildModel({ catalog: readCatalog(catalogPath), skillsRoot, std });
  const report = createReporter({ name: 'build-catalog' });
  for (const problem of model.problems) report.problem(problem);

  // A root .claude-plugin/plugin.json is shared by both "source": "./" entries and its name wins over theirs,
  // so every games skill would load as react-native:<skill> (verified with claude plugin details, 2026-10-17).
  if (existsSync(join(repo, '.claude-plugin', 'plugin.json'))) report.problem({ file: '.claude-plugin/plugin.json', rule: 'plugin-json-present', message: 'exists; both marketplace entries share it and its name replaces theirs, so the games skills would load under the core namespace (and a "skills" key would load every skill in both plugins)', fix: 'Delete it; build-catalog writes each plugin\'s metadata into its .claude-plugin/marketplace.json entry.' });

  const read = (rel) => (existsSync(join(repo, rel)) ? readFileSync(join(repo, rel), 'utf8') : null);
  const outputs = [
    { rel: 'skills.json', text: renderSkillsJson(model) },
    { rel: 'docs/skills-data.js', text: renderSkillsDataJs(model) },
    { rel: '.claude-plugin/marketplace.json', text: renderMarketplace(read('.claude-plugin/marketplace.json'), model) },
  ];
  for (const [rel, markers, block, placeholder] of [['README.md', MARKERS.skills, renderReadmeBlock(model, std), README_PLACEHOLDER], ['AGENTS.md', MARKERS.intents, renderIntentsBlock(model, std), AGENTS_PLACEHOLDER]]) {
    const current = read(rel);
    if (current === null) {
      if (options.check) report.problem({ file: rel, rule: 'generated-missing', message: 'does not exist', fix: 'Run: node tools/build-catalog.mjs' });
      else outputs.push({ rel, text: replaceBlock(placeholder, markers, block), created: true });
      continue;
    }
    const replaced = replaceBlock(current, markers, block);
    if (replaced !== null) outputs.push({ rel, text: replaced });
    else if (options.check) report.problem({ file: rel, rule: 'generated-markers', message: `has no ${markers.start} ... ${markers.end} block`, fix: 'Run node tools/build-catalog.mjs (it appends the block), then move it where it belongs.' });
    else outputs.push({ rel, text: `${current.replace(/\s*$/, '\n')}\n${block}\n`, appended: true });
  }

  for (const output of outputs) {
    const current = read(output.rel);
    if (current === output.text) {
      report.note(`ok     ${output.rel}`);
      continue;
    }
    if (options.check) {
      report.problem({ file: output.rel, rule: current === null ? 'generated-missing' : 'generated-stale', message: current === null ? 'does not exist' : 'differs from what tools/catalog.json and the skills generate', fix: 'Run: node tools/build-catalog.mjs (never edit generated output by hand).' });
      continue;
    }
    mkdirSync(dirname(join(repo, output.rel)), { recursive: true });
    writeFileSync(join(repo, output.rel), output.text);
    report.note(`${output.created || current === null ? 'create' : output.appended ? 'append' : 'write '} ${output.rel}`);
  }
  if (model.notes.length) report.note(`${model.notes.length} frontmatter names differ from their folders (validate-skills --rule name-match lists them)`);
  report.note(`catalogue: ${model.skills.length} skills on disk (${PLUGINS.map((plugin) => `${plugin.name} ${model.skills.filter((skill) => skill.plugin === plugin.name).length}`).join(', ')}); ${model.planned.length} planned in tools/catalog.json but not on disk yet${model.planned.length ? `: ${model.planned.join(', ')}` : ''}`);
  return report.finish({ checked: outputs.length + model.skills.length, unit: 'files and skills' });
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) run(main);
