// scripts/ads/skadnetwork-list.ts
// The SKAdNetwork list as data: read the identifiers out of Google's page, refuse a page that does
// not look like the list, render the generated module, and compare it with the committed one. Pure;
// refresh-skadnetwork.ts does the network and file work.

/** Google's AdMob iOS quick-start page, which lists the SKAdNetwork IDs of Google and its buyers. */
export const SKADNETWORK_SOURCE = 'https://developers.google.com/admob/ios/quick-start';
/** The generated module app.config.ts imports. */
export const SKADNETWORK_TARGET = 'src/config/skadnetwork-ids.ts';
/** Google's list starts with Google's own identifier; fewer than this many means a changed page. */
export const SKADNETWORK_FIRST = 'cstr6suwn9.skadnetwork';
export const SKADNETWORK_MIN_COUNT = 40;

const ID = /\b[a-z0-9]{10}\.skadnetwork\b/g;

/** Every unique identifier in `text`, in order. */
export function extractSkadnetworkIds(text: string): string[] {
  return [...new Set(text.match(ID) ?? [])];
}

/** Throws unless `ids` look like Google's list (its first entry, at least 40 IDs). */
export function assertGoogleList(ids: readonly string[]): void {
  if (ids[0] !== SKADNETWORK_FIRST || ids.length < SKADNETWORK_MIN_COUNT) {
    throw new Error(
      `unexpected page content (${String(ids.length)} ids, first ${ids[0] ?? 'none'}): refusing to overwrite`,
    );
  }
}

/** The generated TypeScript module (TypeScript, so app.config.ts imports it without attributes). */
export function skadnetworkModuleSource(ids: readonly string[]): string {
  const lines = ids.map((id) => `  '${id}',`).join('\n');
  return `// ${SKADNETWORK_TARGET}\n// GENERATED by refresh-skadnetwork.ts from ${SKADNETWORK_SOURCE}. Do not edit.\nexport const SKADNETWORK_IDS: readonly string[] = [\n${lines}\n];\n`;
}

/** What changed between the committed list and Google's. */
export function diffSkadnetworkIds(
  committed: readonly string[],
  fresh: readonly string[],
): { readonly added: readonly string[]; readonly removed: readonly string[] } {
  return {
    added: fresh.filter((id) => !committed.includes(id)),
    removed: committed.filter((id) => !fresh.includes(id)),
  };
}
