function checkVectorsFile(ctx, g) {
  const { root, report } = ctx;
  const vectors = readJson(root, g.vectors);
  const problem = (message, line = 1) => report.problem({ file: g.vectors, line, rule: 'vectors-file', message, fix: FIX['vectors-file'] });
  if (!vectors.exists) return problem(`the vectors file of ${g.id} does not exist${ROOT_HINT}`), null;
  if (vectors.error) return problem(`not valid JSON (${vectors.error})`), null;
  const data = vectors.data;
  if (!isObject(data) || !Array.isArray(data.rows)) return problem('has no "rows" list'), null;
  if (data.generator !== g.id) problem(`"generator" is ${JSON.stringify(data.generator)}, not "${g.id}"`, lineOfText(vectors.text, '"generator"'));
  if (data.fingerprint !== spec.FINGERPRINT_ALGORITHM) problem(`"fingerprint" is ${JSON.stringify(data.fingerprint)}, not "${spec.FINGERPRINT_ALGORITHM}"`, lineOfText(vectors.text, '"fingerprint"'));
  if (typeof data.oracle !== 'string' || data.oracle.trim() === '') problem('names no "oracle" (the repo-relative path of the file that computed the rows)');
  const versions = new Set(g.versions.map((entry) => entry.version));
  const seen = new Set();
  const rows = [];
  for (const row of data.rows) {
    const where = isObject(row) && typeof row.key === 'string' ? lineOfText(vectors.text, `"key": "${row.key}"`) : 1;
    const issues = [];
    if (!isObject(row)) issues.push('a row is not an object');
    else {
      if (typeof row.key !== 'string' || (g.keyKind === 'date' && !spec.isSpecDateKey(row.key))) issues.push(`key ${JSON.stringify(row.key)} is not a ${g.keyKind === 'date' ? 'real civil date (YYYY-MM-DD)' : 'string'}`);
      if (!versions.has(row.version)) issues.push(`version ${JSON.stringify(row.version)} is not in the cutover table`);
      if (typeof row.fingerprint !== 'string' || !/^[0-9a-f]{8}$/.test(row.fingerprint)) issues.push(`fingerprint ${JSON.stringify(row.fingerprint)} is not 8 lowercase hex digits (fill it with the oracle)`);
      if (g.summarize && typeof row.summary !== 'string') issues.push('has no "summary" (the line a reviewer reads)');
      if (typeof row.note !== 'string' || row.note.trim() === '') issues.push('has no "note" (why the row exists)');
      if (seen.has(`${row.key}@${row.version}`)) issues.push(`${row.key} at version ${row.version} is listed twice`);
      seen.add(`${row.key}@${row.version}`);
    }
    if (issues.length > 0) problem(`row ${isObject(row) ? JSON.stringify(row.key) : '?'}: ${issues.join('; ')}`, where);
    else rows.push(row);
  }
  return { data, text: vectors.text, rows };
}

function checkCover(ctx, g, vectors) {
  const { report } = ctx;
  const all = vectors.data.rows.filter(isObject);
  const has = (key, version) => all.some((row) => row.key === key && row.version === version);
  const missing = [];
  if (all.length < 3) missing.push('at least 3 rows');
  for (const entry of g.versions) if (!all.some((row) => row.version === entry.version)) missing.push(`a row for version ${entry.version}`);
  if (g.keyKind === 'date') {
    for (const entry of g.versions.slice(1)) {
      if (!spec.isSpecDateKey(entry.from)) continue;
      const before = spec.specAddDays(entry.from, -1);
      if (!has(before, entry.version - 1)) missing.push(`${before} at version ${entry.version - 1} (the day before the cutover)`);
      if (!has(entry.from, entry.version)) missing.push(`${entry.from} at version ${entry.version} (the cutover day)`);
    }
    const keys = new Set(all.map((row) => row.key));
    const rollover = [...keys].some((key) => /-12-31$/.test(key) && keys.has(`${String(Number(key.slice(0, 4)) + 1).padStart(4, '0')}-01-01`));
    if (!rollover) missing.push('a year-end and new-year pair (YYYY-12-31 and the next YYYY-01-01)');
    if (![...keys].some((key) => key.endsWith('-02-29'))) missing.push('a leap day (YYYY-02-29)');
  }
  if (missing.length > 0) report.problem({ file: g.vectors, line: 1, rule: 'vectors-cover', message: `the rows lack ${missing.join(', ')}`, fix: FIX['vectors-cover'] });
}

/** The app's own code folders: the root src/ and each workspace's src/ (an oracle may reach none). */
function appCodeDirs(layout) {
  return [...new Set([layout.srcDir, ...(layout.workspaces ?? []).map((entry) => entry.layout?.srcDir).filter((dir) => typeof dir === 'string')])];
}

function checkOracle(ctx, g, vectors) {
  const { root, report, layout } = ctx;
  const oracle = vectors.data.oracle;
  if (typeof oracle !== 'string' || oracle.trim() === '') return;
  const problem = (message, file = g.vectors, line = lineOfText(vectors.text, '"oracle"')) => report.problem({ file, line, rule: 'oracle-independent', message, fix: FIX['oracle-independent'] });
  const value = oracle.trim();
  if (/\s/.test(value)) return problem(`"oracle" is a command (${value}), not a file: name the oracle by its repo-relative path (a Python oracle is fine), so the checker can read it`);
  const rel = posix.normalize(value);
  if (rel.startsWith('../') || posix.isAbsolute(rel)) return problem(`"oracle" ${value} is not a repo-relative path`);
  if (rel === posix.normalize(g.module)) return problem('the oracle is the generator itself: the rows would agree with its bugs');
  if (!existsSync(join(root, rel))) return problem(`the oracle ${rel} does not exist`);
  if (!SCRIPT_EXTENSIONS.test(rel)) return;
  // Follow the oracle's local imports (relative, tsconfig aliases, workspace packages; never
  // node_modules) through every helper it reaches: one re-exporting file must not hide app code.
  const appDirs = appCodeDirs(layout);
  const appDirOf = (path) => appDirs.find((dir) => path === dir || path.startsWith(`${dir}/`));
  const moduleStem = g.module.replace(/\.m?ts$/, '');
  const visited = new Set([rel]);
  const queue = [[rel]];
  while (queue.length > 0) {
    const chain = queue.shift();
    const file = chain.at(-1);
    const source = readFileSync(join(root, file), 'utf8');
    const lineAt = (index) => source.slice(0, index).split('\n').length;
    for (const { from, index } of moduleSpecifiers(source)) {
      const resolved = resolveImport(file, from, { root, aliases: layout.aliases });
      if (resolved.kind !== 'local' || typeof resolved.path !== 'string') continue;
      const target = posix.normalize(resolved.path);
      if (target.startsWith('../')) continue;
      const appDir = appDirOf(target);
      if (appDir !== undefined) {
        const message = chain.length === 1
          ? `the oracle imports ${from} from ${appDir}/: it must share no code with the app`
          : `the oracle reaches ${target} through ${[...chain, target].join(' -> ')}: it must share no code with the app`;
        problem(message, file, lineAt(index));
      } else if (resolved.exists && SCRIPT_EXTENSIONS.test(target) && !visited.has(target)) {
        visited.add(target);
        queue.push([...chain, target]);
      }
    }
    if (maskComments(source).includes(moduleStem)) {
      const through = chain.length > 1 ? ` through ${chain.join(' -> ')}` : '';
      problem(`the oracle reads the generator source (${moduleStem})${through}`, file, lineOfText(source, moduleStem));
    }
  }
}

function checkVectorsTest(ctx, g) {
  const { root, report } = ctx;
  const folder = posix.dirname(g.module);
  const vectorsName = posix.basename(g.vectors);
  const tests = existsSync(join(root, folder)) ? walk(join(root, folder)).filter((rel) => isTestFile(rel)) : [];
  const found = tests.some((rel) => {
    const text = readFileSync(join(root, folder, rel), 'utf8');
    return text.includes(vectorsName.replace(/\.json$/, '')) && text.includes(g.generate);
  });
  if (!found) report.problem({ file: g.vectors, line: 1, rule: 'vectors-test', message: `no test in ${folder}/ imports ${vectorsName} and runs ${g.generate}, so CI never verifies the rows`, fix: FIX['vectors-test'] });
}

function checkOutcome(ctx, g) {
  const { root, report } = ctx;
  if (g.outcome === null) return;
  const reason = notYetCreated(root, { file: g.outcome.file, owner: 'persistence-and-migrations' });
  if (reason) {
    report.skip({ file: g.outcome.file, rule: 'outcome-version', message: reason });
    return;
  }
  const text = maskComments(readFileSync(join(root, g.outcome.file), 'utf8'));
  if (!new RegExp(`\\b${g.outcome.versionField}\\b`).test(text)) {
    report.problem({ file: g.outcome.file, line: 1, rule: 'outcome-version', message: `the stored ${g.id} outcome has no ${g.outcome.versionField} field, so replay cannot pick the version the user saw`, fix: FIX['outcome-version'] });
  }
}

/**
 * What a gate line must contain to run the regeneration: the whole command, or its script path with
 * the same arguments (`node ./scripts/oracles/update-x.ts` and `tsx scripts/oracles/update-x.ts` both
 * count). With arguments (`python3 scripts/oracles/x.py --fill`) the path alone is not enough: CI may
 * run the same oracle in its verify mode.
 */
function blessTokens(g) {
  const words = g.regenerate.trim().split(/\s+/);
  const tokens = new Set([words.join(' ')]);
  words.forEach((word, index) => {
    if (word.includes('/') && /\.\w+$/.test(word)) tokens.add([word.replace(/^\.\//, ''), ...words.slice(index + 1)].join(' '));
  });
  return [...tokens];
}

