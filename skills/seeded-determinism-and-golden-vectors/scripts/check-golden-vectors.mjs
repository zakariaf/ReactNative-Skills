function localToday() {
  const now = new Date();
  const pad = (value) => String(value).padStart(2, '0');
  return `${String(now.getFullYear()).padStart(4, '0')}-${pad(now.getMonth() + 1)}-${pad(now.getDate())}`;
}

/**
 * The committed state the frozen rules compare with: --committed-dir (a folder holding the app as
 * committed or shipped), else git (--committed-ref, default HEAD). `read(rel)` is the file's text or
 * null; `where(rel)` names it in messages; `missing` says why there is no baseline at all.
 */
function openBaseline(root, options) {
  const dir = options['committed-dir'];
  const ref = options['committed-ref'];
  if (dir !== undefined && ref !== undefined) fail('--committed-dir and --committed-ref both name a baseline', 'Pass one of them: --committed-ref for a git revision, --committed-dir for an exported folder.');
  if (dir !== undefined) {
    const abs = isAbsolute(dir) ? dir : join(root, dir);
    if (!existsSync(abs) || !statSync(abs).isDirectory()) fail(`--committed-dir ${dir} is not a folder`, 'Pass a folder that holds the app as last committed, for example after: git worktree add ../base origin/main');
    return {
      missing: null,
      where: (rel) => posix.join(toPosix(dir), rel),
      read: (rel) => (existsSync(join(abs, rel)) ? readFileSync(join(abs, rel), 'utf8') : null),
    };
  }
  const revision = ref ?? 'HEAD';
  const git = (args) => execFileSync('git', ['-C', root, ...args], { encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'], timeout: 15000 });
  try {
    git(['rev-parse', '--verify', '--quiet', `${revision}^{commit}`]);
  } catch {
    if (ref !== undefined) fail(`--committed-ref ${ref} is not a commit of a git repository at the root`, 'Fetch it first (git fetch --depth 1 origin main) and pass origin/main, a release tag or a commit hash, or export it and pass --committed-dir.');
    return { missing: 'the root is not inside a git repository with a commit', where: (rel) => rel, read: () => null };
  }
  return {
    missing: null,
    where: (rel) => `git ${revision}:${rel}`,
    read: (rel) => {
      try {
        return git(['show', `${revision}:./${rel}`]);
      } catch {
        return null;
      }
    },
  };
}

/** The committed contract: { source, generators, retired } or { absent: '<why>' }. */
function readCommittedContract(baseline, contractRel) {
  if (baseline.missing !== null) return { absent: `no committed baseline (${baseline.missing}; pass --committed-ref or --committed-dir)` };
  const source = baseline.where(contractRel);
  const text = baseline.read(contractRel);
  if (text === null) return { absent: `${source} does not exist (nothing is committed yet, so nothing is frozen)` };
  let data;
  try {
    data = JSON.parse(text);
  } catch (error) {
    return { absent: `${source} is not valid JSON (${String(error.message).split('\n')[0]})` };
  }
  const list = (key) => (isObject(data) && Array.isArray(data[key]) ? data[key].filter((entry) => isObject(entry) && typeof entry.id === 'string') : []);
  return { source, generators: list('generators'), retired: list('retired') };
}

/**
 * Pairs each current generator with its committed entry: by id, else (a rename) a committed entry whose
 * id is gone and that has the same module, vectors file or salt. Returns { pairs: Map<id, { entry,
 * renamedFrom, via }>, gone: [committed entries with no current generator] }.
 */
function pairCommitted(generators, committed) {
  const pairs = new Map();
  if (committed.generators === undefined) return { pairs, gone: [] };
  const current = generators.filter((g) => isObject(g) && typeof g.id === 'string');
  const currentIds = new Set(current.map((g) => g.id));
  const byId = new Map(committed.generators.map((entry) => [entry.id, entry]));
  const orphans = committed.generators.filter((entry) => !currentIds.has(entry.id));
  const claimed = new Set();
  for (const g of current) {
    if (byId.has(g.id)) {
      pairs.set(g.id, { entry: byId.get(g.id), renamedFrom: null, via: null });
      continue;
    }
    for (const via of ['module', 'vectors', 'salt']) {
      const entry = orphans.find((candidate) => !claimed.has(candidate.id) && g[via] !== undefined && candidate[via] === g[via]);
      if (entry === undefined) continue;
      claimed.add(entry.id);
      pairs.set(g.id, { entry, renamedFrom: entry.id, via });
      break;
    }
  }
  return { pairs, gone: orphans.filter((entry) => !claimed.has(entry.id)) };
}

/** Shape problems of the contract's "retired" list: [{ id, migration, note }]. */
function retiredProblems(data) {
  if (data.retired === undefined) return [];
  if (!Array.isArray(data.retired)) return ['"retired" is not a list of { "id", "migration", "note" }'];
  const problems = [];
  const ids = new Set(data.generators.filter(isObject).map((g) => g.id));
  data.retired.forEach((entry, index) => {
    if (!isObject(entry)) return problems.push(`retired entry ${index} is not an object`);
    for (const key of Object.keys(entry)) if (!RETIRED_KEYS.has(key)) problems.push(`retired entry ${index}: unknown key "${key}"`);
    if (typeof entry.id !== 'string' || !KEBAB.test(entry.id)) problems.push(`retired entry ${index}: "id" is not a kebab-case name`);
    else if (ids.has(entry.id)) problems.push(`retired entry ${index}: ${entry.id} is still registered (a retired id is never reused)`);
    if (!(entry.migration === null || (typeof entry.migration === 'string' && entry.migration.trim() !== ''))) problems.push(`retired entry ${index}: "migration" is not a file path or null`);
    if (typeof entry.note !== 'string' || entry.note.trim() === '') problems.push(`retired entry ${index}: "note" must say why and who approved it`);
    return undefined;
  });
  return problems;
}

/**
 * Committed generators that are no longer registered: each needs a "retired" entry, and one whose stored
 * outcomes the committed contract records needs a migration file that exists.
 */
function goneGenerators(ctx, gone, committed, data, contract) {
  const { root, report, contractRel } = ctx;
  const retired = new Map((Array.isArray(data.retired) ? data.retired : []).filter(isObject).map((entry) => [entry.id, entry]));
  for (const entry of gone) {
    const line = Math.max(1, lineOfText(contract.text, '"generators"'));
    const record = retired.get(entry.id);
    const problem = (message) => report.problem({ file: contractRel, line, rule: 'version-cutover', message, fix: FIX['version-cutover'] });
    if (record === undefined) {
      problem(`generator ${entry.id} recorded in ${committed.source} is gone: a shipped generator is retired with a migration of its stored outcomes, the developer's approval and a "retired" entry, never by deleting or renaming its entry (a renamed generator keeps its module, vectors file or salt)`);
    } else if (isObject(entry.outcome) && typeof record.migration !== 'string') {
      problem(`generator ${entry.id} stored outcomes (${committed.source} names ${JSON.stringify(entry.outcome.file)}), but its "retired" entry names no migration: drop or rewrite those rows first`);
    } else if (typeof record.migration === 'string' && !existsSync(join(root, record.migration))) {
      problem(`generator ${entry.id} is retired with the migration ${record.migration}, which does not exist`);
    } else {
      report.note(`${entry.id}: retired (${record.note.trim()}); ${committed.source} still records it`);
    }
  }
}

/** The committed vectors rows of a paired generator: { source, rows } (filled rows only), or { absent }. */
function committedRows(baseline, g, entry) {
  const rel = typeof entry.vectors === 'string' ? entry.vectors : g.vectors;
  const source = baseline.where(rel);
  const text = baseline.read(rel);
  if (text === null) return { source, absent: `${source} does not exist` };
  try {
    const data = JSON.parse(text);
    const rows = isObject(data) && Array.isArray(data.rows) ? data.rows : [];
    return { source, rows: rows.filter((row) => isObject(row) && typeof row.key === 'string' && typeof row.fingerprint === 'string' && /^[0-9a-f]{8}$/.test(row.fingerprint)) };
  } catch {
    return { source, absent: `${source} is not valid JSON` };
  }
}

/** Versions appended since the committed entry whose cutover is not in the future. */
function retroactiveCutovers(g, before, source, today) {
  if (g.keyKind !== 'date' || !Array.isArray(before.versions)) return [];
  const known = new Set(before.versions.map((entry) => entry?.version));
  return g.versions
    .filter((entry) => !known.has(entry.version) && typeof entry.from === 'string' && entry.from <= today)
    .map((entry) => `version ${entry.version} starts ${entry.from}, on or before today (${today}), and ${source} does not record it yet: keys users have already seen would change on update`);
}

/**
 * Edits of what the committed entry records: a committed version that moved or disappeared, a changed
 * key kind (version-cutover), a changed salt (salt-frozen). Only edits are flagged, so time passing
 * never fails a planned cutover. The template salt may change while every committed row is still a
 * template row: replacing both before the first release is Workflow step 6.
 */
function committedEdits(g, before, source, templateState) {
  const out = [];
  const frozen = 'a committed cutover never moves or disappears; append a new version with a future date';
  if (isUint32(before.salt) && before.salt !== g.salt && !(before.salt === TEMPLATE_SALT && templateState)) {
    const why = before.salt === TEMPLATE_SALT ? ' (the template salt, but the committed rows are no longer the template\'s: it shipped)' : '';
    out.push({ rule: 'salt-frozen', message: `the salt is ${g.salt}, but ${source} records the shipped salt ${before.salt}${why}: a committed salt never changes (a new salt is a new version with a future cutover)` });
  }
  if (['date', 'text'].includes(before.keyKind) && before.keyKind !== g.keyKind) {
    out.push({ rule: 'version-cutover', message: `"keyKind" is "${g.keyKind}", but ${source} records "${before.keyKind}": keys already handed out would route differently` });
  }
  for (const entry of Array.isArray(before.versions) ? before.versions : []) {
    if (!isObject(entry) || !Number.isInteger(entry.version)) continue;
    const was = entry.from ?? null;
    const now = g.versions.find((current) => current.version === entry.version);
    if (now === undefined) out.push({ rule: 'version-cutover', message: `version ${entry.version} (from ${JSON.stringify(was)}) is recorded in ${source} but is gone: ${frozen}` });
    else if ((now.from ?? null) !== was) out.push({ rule: 'version-cutover', message: `version ${entry.version} now starts ${JSON.stringify(now.from)}, but ${source} records ${JSON.stringify(was)}: ${frozen}` });
  }
  return out;
}

/** Every filled committed row keeps its fingerprint and summary; the template rows are the exception. */
function checkVectorsFrozen(ctx, g, frozen, vectors) {
  const { report } = ctx;
  if (frozen.rows === undefined || !vectors) return;
  const current = vectors.data.rows.filter(isObject);
  const describe = (row) => (typeof row.fingerprint === 'string' && row.fingerprint !== '' ? `${row.fingerprint}${typeof row.summary === 'string' ? ` "${row.summary}"` : ''}` : 'unfilled');
  for (const row of frozen.rows) {
    if (isTemplateRow(row)) continue;
    const now = current.find((candidate) => candidate.key === row.key && candidate.version === row.version);
    const at = `${row.key} at version ${row.version}`;
    if (now === undefined) {
      report.problem({ file: g.vectors, line: Math.max(1, lineOfText(vectors.text, '"rows"')), rule: 'vectors-frozen', message: `${at} (${describe(row)}) is recorded in ${frozen.source} but is gone from the rows: a committed row is never deleted`, fix: FIX['vectors-frozen'] });
    } else if (now.fingerprint !== row.fingerprint || (typeof row.summary === 'string' && now.summary !== row.summary)) {
      report.problem({ file: g.vectors, line: lineOfText(vectors.text, `"key": "${row.key}"`), rule: 'vectors-frozen', message: `${at} was ${describe(row)} in ${frozen.source} and is now ${describe(now)}: a committed row never changes`, fix: FIX['vectors-frozen'] });
    }
  }
}

/** A generator still on the template's salt or catalog gets a reminder (nothing proves whether it shipped). */
function templateNote(report, g, vectors) {
  const parts = [];
  if (g.salt === TEMPLATE_SALT) parts.push(`the salt ${TEMPLATE_SALT}`);
  if (vectors && vectors.data.rows.some((row) => isObject(row) && typeof row.summary === 'string' && /\bitem-\d{2}\b/.test(row.summary))) parts.push('the item-01 ... item-12 catalog');
  if (parts.length > 0) report.note(`${g.id}: template values still in use (${parts.join(', ')}): replace them before the first release (Workflow step 6); the checker cannot tell whether this generator has shipped`);
}

// ---------------------------------------------------------------------------------------------

async function main() {
  const { options, positionals } = parseArgs(process.argv.slice(2), SPEC);
  const root = requireDir(positionals[0] ?? '.', 'repo root');
  const layout = resolveLayout(root);
  const contractRel = options.contract ?? posix.join(layout.contractsDir, 'seeded-generators.json');
  const contract = readJson(root, contractRel);
  if (!contract.exists) fail(`nothing to check: ${contractRel} does not exist`, 'Copy templates/contracts/seeded-generators.json and register each seeded generator ("generators": [] when the app has none).');
  if (contract.error) fail(`${contractRel} is not valid JSON (${contract.error})`, 'Fix the JSON.');
  if (options.today !== undefined && !spec.isSpecDateKey(options.today)) fail(`--today ${options.today} is not a civil date (YYYY-MM-DD)`, 'Pass a real calendar day, for example --today 2026-10-03.');
  const report = createReporter({ name: 'check-golden-vectors', json: options.json });
  const data = contract.data;
  if (!isObject(data) || !Array.isArray(data.generators) || (data.paths !== undefined && !(Array.isArray(data.paths) && data.paths.every((entry) => typeof entry === 'string')))) {
    report.problem({ file: contractRel, line: 1, rule: 'contract-shape', message: 'the contract is not { "paths": [<glob>], "generators": [ ... ], "retired"?: [ ... ] }', fix: FIX['contract-shape'] });
    return report.finish({ checked: 0, unit: 'generators' });
  }
  const retiredIssues = retiredProblems(data);
  if (retiredIssues.length > 0) report.problem({ file: contractRel, line: Math.max(1, lineOfText(contract.text, '"retired"')), rule: 'contract-shape', message: retiredIssues.join('; '), fix: FIX['contract-shape'] });
  const wanted = options.generator ?? [];
  for (const id of wanted) if (!data.generators.some((g) => g?.id === id)) fail(`no generator "${id}" in ${contractRel}`, 'Pass an id the contract declares.');
  const today = options.today ?? localToday();
  const baseline = openBaseline(root, options);
  const committed = readCommittedContract(baseline, contractRel);
  const ctx = { root, layout, report, contractRel, app: null, workspaceRoot: enclosingWorkspaceRoot(root) };
  // Removed or renamed generators are found before anything else, so "generators": [] cannot hide them.
  const { pairs, gone } = pairCommitted(data.generators, committed);
  if (wanted.length === 0) goneGenerators(ctx, gone, committed, data, contract);
  if (data.generators.length === 0) {
    if (report.problems.length > 0) return report.finish({ checked: 0, unit: 'generators' });
    return report.notApplicable(`${contractRel} declares no seeded generators ("generators": [])`);
  }
  if (committed.absent !== undefined) report.note(`frozen checks: ${committed.absent}: committed generators, salts, cutovers and vectors rows were not compared`);
  ctx.app = enableAppImports(root);
  const seenIds = new Set();
  const salts = new Map();
  let checked = 0;
  for (const g of data.generators) {
    const problems = shapeProblems(g, seenIds);
    if (isObject(g) && typeof g.id === 'string') seenIds.add(g.id);
    if (wanted.length > 0 && !wanted.includes(g?.id)) continue;
    const line = isObject(g) && typeof g.id === 'string' ? lineOfText(contract.text, `"id": "${g.id}"`) : 1;
    const label = isObject(g) && typeof g.id === 'string' ? g.id : '?';
    if (problems.length > 0) {
      report.problem({ file: contractRel, line, rule: 'contract-shape', message: `${label}: ${problems.join('; ')}`, fix: FIX['contract-shape'] });
      continue;
    }
    const tableProblems = versionTableProblems(g);
    if (tableProblems.length > 0) {
      report.problem({ file: contractRel, line, rule: 'version-cutover', message: `${label}: ${tableProblems.join('; ')}`, fix: FIX['version-cutover'] });
      continue;
    }
    checked += 1;
    const saltLine = lineOfText(contract.text.slice(contract.text.indexOf(`"id": "${g.id}"`)), '"salt"') + line - 1;
    const vectors = checkVectorsFile(ctx, g);
    const pair = pairs.get(g.id);
    if (pair !== undefined) {
      const { entry, renamedFrom, via } = pair;
      if (renamedFrom !== null) report.note(`${g.id}: compared with ${renamedFrom} in ${committed.source} (same ${via}): treated as a rename`);
      const frozen = committedRows(baseline, g, entry);
      if (frozen.absent !== undefined) report.note(`frozen checks: ${g.id}: ${frozen.absent}, so its committed rows were not compared`);
      const templateState = (frozen.rows ?? []).every(isTemplateRow);
      for (const message of retroactiveCutovers(g, entry, committed.source, today)) report.problem({ file: contractRel, line, rule: 'version-cutover', message: `${label}: ${message}`, fix: FIX['version-cutover'] });
      for (const { rule, message } of committedEdits(g, entry, committed.source, templateState)) report.problem({ file: contractRel, line: rule === 'salt-frozen' ? saltLine : line, rule, message: `${label}: ${message}`, fix: FIX[rule] });
      checkVectorsFrozen(ctx, g, frozen, vectors);
    }
    if (salts.has(g.salt)) report.problem({ file: contractRel, line: saltLine, rule: 'salt-frozen', message: `${g.id} uses the salt ${g.salt} of ${salts.get(g.salt)}: their outputs would move together`, fix: FIX['salt-frozen'] });
    salts.set(g.salt, g.id);
    templateNote(report, g, vectors);
    if (vectors) {
      checkCover(ctx, g, vectors);
      checkOracle(ctx, g, vectors);
    }
    checkVectorsTest(ctx, g);
    checkOutcome(ctx, g);
    checkNoAutoBless(ctx, g);
    await checkRuntime(ctx, g, vectors);
  }
  return report.finish({ checked, unit: 'generators' });
}

run(main);
