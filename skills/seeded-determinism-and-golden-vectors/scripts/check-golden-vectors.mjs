async function loadGenerator(ctx, g) {
  const { root, report } = ctx;
  const problem = (message, line = 1) => report.problem({ file: g.module, line, rule: 'generator-pure', message, fix: FIX['generator-pure'] });
  if (!/\.m?ts$/.test(g.module) || g.module.endsWith('.d.ts')) return problem('the generator module must be a .ts file (JSX and platform files are not pure)'), null;
  if (!existsSync(join(root, g.module))) return problem(`the generator module of ${g.id} does not exist${ROOT_HINT}`), null;
  const source = readFileSync(join(root, g.module), 'utf8');
  let mod;
  try {
    mod = await ctx.app.load(g.module);
  } catch (error) {
    return problem(`cannot be imported in plain Node, so it is not pure: ${errorText(error)}`), null;
  }
  const missing = [g.generate, g.summarize].filter((name) => name && typeof mod[name] !== 'function');
  if (typeof mod[g.saltExport] !== 'number') missing.push(`${g.saltExport} (a number)`);
  if (!Array.isArray(mod[g.versionsExport])) missing.push(`${g.versionsExport} (the cutover table)`);
  if (missing.length > 0) return problem(`does not export ${missing.join(', ')}`), null;
  return { mod, source };
}

/**
 * A text key (a share code, a typed seed) has no cutover date: the version travels with the key. Each
 * explicit call must stamp the version it was asked for, and a call without a version must either
 * throw or return the version the key itself carries, never quietly pick the newest.
 */
function textKeyFindings(g, rows, generate, add) {
  const unstamped = [];
  const defaulted = [];
  for (const row of rows) {
    try {
      const output = generate(row.key, row.version);
      if (!output || output.version !== row.version) unstamped.push(row);
    } catch {
      // vectors-match already reports a row that throws.
    }
    if (g.versions.length < 2) continue;
    let routed = null;
    try {
      routed = generate(row.key);
    } catch {
      routed = null;
    }
    if (routed !== null && routed?.version !== row.version) defaulted.push({ row, got: routed?.version });
  }
  const more = (list) => (list.length > 1 ? ` (and ${list.length - 1} more row${list.length > 2 ? 's' : ''})` : '');
  if (unstamped.length > 0) {
    const [row] = unstamped;
    add('version-cutover', `${g.generate}('${row.key}', ${row.version}) does not stamp the version it used (a numeric "version" field equal to ${row.version})${more(unstamped)}`, row.key);
  }
  if (defaulted.length > 0) {
    const [{ row, got }] = defaulted;
    add('version-cutover', `${g.generate}('${row.key}') without a version returns version ${String(got)}, but the row's key was made with version ${row.version}${more(defaulted)}: a text-keyed generator has no cutover, so callers pass the version the key carries (or the generator reads it from the key)`, row.key);
  }
}

function runtimeFindings(g, mod, rows, hits) {
  const out = [];
  const add = (rule, message, rowKey = null, at = null) => out.push({ rule, message, rowKey, at });
  const generate = (key, version) => {
    const value = withAmbientTraps(() => (version === undefined ? mod[g.generate](key) : mod[g.generate](key, version)), hits);
    if (value && typeof value.then === 'function') throw new TypeError(`${g.generate} returns a Promise: a generator is synchronous`);
    return value;
  };
  const summarize = (output) => withAmbientTraps(() => mod[g.summarize](output), hits);
  const tryRun = (rule, rowKey, fn) => {
    try {
      fn();
    } catch (error) {
      add(rule, `${rowKey ?? g.generate}: ${errorText(error)}`, rowKey);
    }
  };
  const versions = mod[g.versionsExport].map((entry) => ({ version: entry?.version, from: entry?.from ?? null }));
  if (JSON.stringify(versions) !== JSON.stringify(g.versions.map(({ version, from }) => ({ version, from })))) add('version-cutover', `${g.versionsExport} in code is ${JSON.stringify(versions)}; the contract records ${JSON.stringify(g.versions)}`, null, g.versionsExport);
  for (const row of rows) {
    tryRun('vectors-match', row.key, () => {
      const output = generate(row.key, row.version);
      const got = spec.specFingerprint(output);
      const summary = g.summarize ? summarize(output) : undefined;
      const summaryDiffers = g.summarize && row.summary !== undefined && summary !== row.summary;
      if (got !== row.fingerprint || summaryDiffers) {
        const reads = summaryDiffers ? ` and reads "${summary}" (the row reads "${row.summary}")` : '';
        add('vectors-match', `${row.key} at version ${row.version} now fingerprints ${got} (the row holds ${row.fingerprint})${reads}`, row.key);
      }
    });
    if (g.keyKind === 'date') {
      tryRun('version-cutover', row.key, () => {
        const routed = generate(row.key);
        const want = route(g.versions, row.key);
        if (!routed || typeof routed.version !== 'number') add('version-cutover', `${g.generate}('${row.key}') does not stamp the version it used (a numeric "version" field)`, row.key);
        else if (routed.version !== want) add('version-cutover', `${g.generate}('${row.key}') uses version ${routed.version}; the cutover table gives ${want}`, row.key);
      });
    }
  }
  const [first, second] = rows;
  if (g.keyKind === 'text') textKeyFindings(g, rows, generate, add);
  if (first) {
    tryRun('repeatable-run', first.key, () => {
      const a = spec.specCanonicalJson(generate(first.key, first.version));
      const b = spec.specCanonicalJson(generate(first.key, first.version));
      if (second) generate(second.key, second.version);
      const c = spec.specCanonicalJson(generate(first.key, first.version));
      if (a !== b || a !== c) add('repeatable-run', `${g.generate}('${first.key}', ${first.version}) returns different output on another call: the generator keeps state between calls`, first.key);
    });
  }
  return out;
}

async function checkRuntime(ctx, g, vectors) {
  const { report } = ctx;
  const rows = vectors?.rows ?? [];
  const rowLine = (key) => (vectors && key ? lineOfText(vectors.text, `"key": "${key}"`) : 1);
  const loaded = await loadGenerator(ctx, g);
  if (!loaded) return;
  const { mod, source } = loaded;
  if (mod[g.saltExport] !== g.salt) report.problem({ file: g.module, line: lineOfExport(source, g.saltExport), rule: 'salt-frozen', message: `${g.saltExport} is ${mod[g.saltExport]}; the contract records the shipped salt ${g.salt}`, fix: FIX['salt-frozen'] });
  const hits = new Set();
  const findings = runtimeFindings(g, mod, rows, hits);
  const line = lineOfExport(source, g.generate);
  if (hits.size > 0) {
    for (const name of hits) report.problem({ file: g.module, line, rule: 'runtime-ambient', message: `${g.generate}() called ${name} while generating a vector row`, fix: FIX['runtime-ambient'] });
    return;
  }
  for (const { rule, message, rowKey, at } of findings) {
    const inVectors = rule === 'vectors-match';
    const where = at ? lineOfExport(source, at) : line;
    report.problem({ file: inVectors ? g.vectors : g.module, line: inVectors ? rowLine(rowKey) : where, rule, message, fix: FIX[rule] });
  }
}

