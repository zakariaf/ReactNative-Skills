/** Folders of gate files: EAS Workflows (Expo's own CI), GitHub workflows and composite actions, Buildkite, husky. */
const GATE_FOLDERS = [
  { dir: '.eas/workflows', recursive: false, name: /\.ya?ml$/ },
  { dir: '.github/workflows', recursive: false, name: /\.ya?ml$/ },
  { dir: '.github/actions', recursive: true, name: /\.ya?ml$/ },
  { dir: '.buildkite', recursive: true, name: /\.ya?ml$/ },
  { dir: '.husky', recursive: false, name: /^[^.]/ },
];

function gateFiles(root) {
  const files = [];
  for (const { dir, recursive, name } of GATE_FOLDERS) {
    const abs = join(root, dir);
    if (!existsSync(abs)) continue;
    for (const entry of readdirSync(abs, { withFileTypes: true, recursive })) {
      if (!entry.isFile() || !name.test(entry.name)) continue;
      files.push(toPosix(relative(root, join(entry.parentPath, entry.name))));
    }
  }
  for (const rel of GATE_FILES) if (existsSync(join(root, rel))) files.push(rel);
  return [...new Set(files)].sort();
}

/**
 * Hook commands kept in package.json: "simple-git-hooks" and husky 4's "husky": { "hooks" } (hook ->
 * command), and "lint-staged" (glob -> command or list of commands): [{ where, command, section }].
 */
function packageHookCommands(manifest) {
  const out = [];
  const hooks = (section, label, value) => {
    if (!isObject(value)) return;
    for (const [hook, command] of Object.entries(value)) if (typeof command === 'string') out.push({ where: `the ${label} ${hook} hook`, command, section });
  };
  hooks('simple-git-hooks', '"simple-git-hooks"', manifest['simple-git-hooks']);
  if (isObject(manifest.husky)) hooks('husky', '"husky"', manifest.husky.hooks);
  if (isObject(manifest['lint-staged'])) {
    for (const [glob, value] of Object.entries(manifest['lint-staged'])) {
      for (const command of Array.isArray(value) ? value : [value]) if (typeof command === 'string') out.push({ where: `the "lint-staged" task for ${JSON.stringify(glob)}`, command, section: 'lint-staged' });
    }
  }
  return out;
}

const escapeRegExp = (text) => text.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
/**
 * Runner flags before or after `run`: `--silent`, `--workspace=apps/mobile`, and the workspace flags that
 * take their value as the next word (`-w apps/mobile`, `--prefix apps/mobile`, pnpm's `--filter`/`-F`/`-C`,
 * bun's `--cwd`), plus yarn's `workspace <name>` subcommand.
 */
const RUNNER_FLAGS = String.raw`(?:\s+(?:(?:-w|-F|-C|--workspace|--prefix|--filter|--dir|--cwd)\s+(?!-)\S+|workspace\s+(?!-)\S+|--?[A-Za-z][\w-]*(?:=\S+)?))*`;

/**
 * A command line that runs the package script `name`: npm, pnpm, yarn or bun (with or without run /
 * run-script, flags allowed), npx --no -- <name>, npm-run-all / run-s / run-p, concurrently's npm:<name>.
 */
function scriptCallPattern(name) {
  const n = escapeRegExp(name);
  return new RegExp(String.raw`(?:\b(?:npm|pnpm|yarn|bun)${RUNNER_FLAGS}(?:\s+(?:run|run-script))?${RUNNER_FLAGS}\s+${n}|\bnpx${RUNNER_FLAGS}\s+--\s+${n}|\b(?:npm-run-all|run-s|run-p)\b[^&|;\n]*?\s${n}|\bnpm:${n})(?![\w:.-])`);
}

/**
 * Every package script that reaches the regeneration, directly or through other scripts: name -> the
 * script it calls (null: runs it itself). `seeds` are scripts already known to reach it (the app's, when
 * the workspace root's scripts are read).
 */
function regenScripts(scripts, tokens, seeds = new Map()) {
  const via = new Map(seeds);
  for (const [name, command] of Object.entries(scripts)) if (typeof command === 'string' && tokens.some((token) => command.includes(token))) via.set(name, null);
  for (let grew = true; grew;) {
    grew = false;
    for (const [name, command] of Object.entries(scripts)) {
      if (via.has(name) || typeof command !== 'string') continue;
      const callee = [...via.keys()].find((candidate) => scriptCallPattern(candidate).test(command));
      if (callee !== undefined) {
        via.set(name, callee);
        grew = true;
      }
    }
  }
  return via;
}

function checkNoAutoBless(ctx, g) {
  const tokens = blessTokens(g);
  const appVia = scanGates(ctx, g, tokens, ctx.root, '', new Map());
  // Inside a workspaces repo the real CI, hooks and scripts usually live at the workspace root.
  if (ctx.workspaceRoot !== null) scanGates(ctx, g, tokens, ctx.workspaceRoot.dir, ctx.workspaceRoot.prefix, appVia);
}

/**
 * Reports every gate in `dir` (the app root, or the workspace root with `prefix`, the parent steps back to it) that runs the
 * regeneration; returns the package scripts there that reach it.
 */
function scanGates(ctx, g, tokens, dir, prefix, seeds) {
  const { report } = ctx;
  const pkg = readJson(dir, 'package.json');
  const scripts = pkg.data && isObject(pkg.data.scripts) ? pkg.data.scripts : {};
  const via = regenScripts(scripts, tokens, seeds);
  const chainFrom = (name) => {
    const chain = [name];
    for (let next = via.get(name); next; next = via.get(next)) chain.push(next);
    return chain;
  };
  /** null when the text does not run the regeneration; else '' (directly) or ' through a -> b'. */
  const reach = (text) => {
    if (tokens.some((token) => text.includes(token))) return '';
    const callee = [...via.keys()].find((name) => scriptCallPattern(name).test(text));
    return callee === undefined ? null : ` through ${chainFrom(callee).join(' -> ')}`;
  };
  const problem = (rel, line, where, through) => report.problem({ file: `${prefix}${rel}`, line, rule: 'no-auto-bless', message: `${where} runs the ${g.id} vectors regeneration (${g.regenerate})${through}: a gate that rewrites what it checks verifies nothing`, fix: FIX['no-auto-bless'] });
  for (const [name, command] of Object.entries(scripts)) {
    if (typeof command !== 'string' || !GATE_SCRIPT.test(name)) continue;
    const through = reach(command);
    if (through !== null) problem('package.json', lineOfText(pkg.text, `"${name}"`), `the "${name}" script`, through);
  }
  for (const { where, command, section } of isObject(pkg.data) ? packageHookCommands(pkg.data) : []) {
    const through = reach(command);
    if (through === null) continue;
    const from = Math.max(0, pkg.text.indexOf(`"${section}"`));
    const at = pkg.text.indexOf(JSON.stringify(command), from);
    problem('package.json', lineOfText(pkg.text, `"${section}"`) + (at < 0 ? 0 : pkg.text.slice(from, at).split('\n').length - 1), where, through);
  }
  for (const rel of gateFiles(dir)) {
    const text = readFileSync(join(dir, rel), 'utf8');
    const hookCommands = AGENT_SETTINGS.test(rel) ? agentHookCommands(text) : null;
    if (hookCommands !== null) {
      // Agent settings: only hooks run commands; a permissions entry that names the command runs nothing.
      for (const command of hookCommands) {
        const through = reach(command);
        if (through !== null) problem(rel, lineOfText(text, JSON.stringify(command)), `the ${prefix}${rel} hook`, through);
      }
      continue;
    }
    for (const { line, index } of /\.ya?ml$/.test(rel) ? yamlCommandLines(text) : plainLines(text)) {
      const through = reach(line);
      if (through !== null) problem(rel, index + 1, `${prefix}${rel}`, through);
    }
  }
  return via;
}

/** Every line that is not a comment: [{ line, index }]. */
function plainLines(text) {
  return text.split('\n').map((line, index) => ({ line, index })).filter(({ line }) => !/^\s*#/.test(line));
}

/**
 * Keys whose values name files, branches or tags, never commands: a GitHub `paths:` filter that starts a
 * review job when the vectors tooling changes, lefthook's `glob:`, pre-commit's `files:`/`exclude:`/
 * `types:`, GitLab's `changes:`.
 */
const YAML_FILTER_KEYS = new Set(['paths', 'paths-ignore', 'branches', 'branches-ignore', 'tags', 'tags-ignore', 'files', 'exclude', 'glob', 'changes', 'types', 'types_or', 'exclude_types']);

/**
 * The lines of a YAML gate file that can run something: every line except comments and the values of a
 * filter key (on the key's line, and the more indented lines or same-indent list items under it).
 */
function yamlCommandLines(text) {
  const out = [];
  let filterIndent = -1;
  text.split('\n').forEach((line, index) => {
    if (/^\s*(?:#|$)/.test(line)) return;
    const indent = line.length - line.trimStart().length;
    if (filterIndent >= 0) {
      if (indent > filterIndent || (indent === filterIndent && /^\s*-(?:\s|$)/.test(line))) return;
      filterIndent = -1;
    }
    const key = /^(\s*(?:-\s+)?)([\w-]+)\s*:(?:\s|$)/.exec(line);
    if (key !== null && YAML_FILTER_KEYS.has(key[2])) {
      filterIndent = key[1].length;
      return;
    }
    out.push({ line, index });
  });
  return out;
}

const AGENT_SETTINGS = /^\.claude\/settings(?:\.local)?\.json$/;

/** Every string under the "hooks" key of an agent settings file, or null when it is not JSON (then it is read line by line). */
function agentHookCommands(text) {
  let data;
  try {
    data = JSON.parse(text);
  } catch {
    return null;
  }
  const out = [];
  const collect = (value) => {
    if (typeof value === 'string') out.push(value);
    else if (Array.isArray(value)) value.forEach(collect);
    else if (isObject(value)) Object.values(value).forEach(collect);
  };
  if (isObject(data)) collect(data.hooks);
  return out;
}

