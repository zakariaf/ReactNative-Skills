// ---------------------------------------------------------------------------------------------
// Ambient traps: clocks, randomness, locale data and the implementation-approximated Math functions
// throw while app code runs. The window covers one generate() or summarize() call; the checker's own
// work (canonical JSON, fingerprints, comparisons) runs outside it, so it can never trip a trap.
// ---------------------------------------------------------------------------------------------

/** Runs `fn` with the traps installed; every trapped name it reaches is added to `hits`. */
function withAmbientTraps(fn, hits) {
  const restores = [];
  const trap = (name) => function trapped() {
    hits.add(name);
    throw new Error(`ambient ${name} called`);
  };
  const replace = (host, key, name, value = trap(name)) => {
    if (!host) return;
    const before = Object.getOwnPropertyDescriptor(host, key);
    try {
      Object.defineProperty(host, key, { configurable: true, writable: true, value });
      restores.push(() => (before ? Object.defineProperty(host, key, before) : delete host[key]));
    } catch {
      // A frozen host object: the text scan in check-determinism still covers it.
    }
  };
  const RealDate = Date;
  const dateTraps = { now: trap('Date.now'), parse: trap('Date.parse'), UTC: trap('Date.UTC') };
  replace(globalThis, 'Date', 'Date', new Proxy(RealDate, {
    construct() {
      hits.add('new Date');
      throw new Error('ambient new Date called');
    },
    apply() {
      hits.add('Date()');
      throw new Error('ambient Date() called');
    },
    get: (target, key) => dateTraps[key] ?? Reflect.get(target, key),
  }));
  replace(Math, 'random', 'Math.random');
  replace(globalThis.performance, 'now', 'performance.now');
  replace(globalThis.crypto, 'getRandomValues', 'crypto.getRandomValues');
  replace(globalThis.crypto, 'randomUUID', 'crypto.randomUUID');
  for (const name of ['Collator', 'DateTimeFormat', 'NumberFormat', 'PluralRules', 'RelativeTimeFormat', 'ListFormat', 'Segmenter', 'DisplayNames', 'Locale']) replace(Intl, name, `Intl.${name}`);
  for (const name of ['localeCompare', 'toLocaleUpperCase', 'toLocaleLowerCase']) replace(String.prototype, name, `String#${name}`);
  replace(Number.prototype, 'toLocaleString', 'Number#toLocaleString');
  replace(Array.prototype, 'toLocaleString', 'Array#toLocaleString');
  // V8 (Jest, Node) and Hermes (the platform's libm) may disagree in the last bit. `**` is an operator
  // and cannot be trapped; check-determinism's text scan, which follows a generator's imports, sees it.
  for (const name of spec.APPROXIMATED_MATH) replace(Math, name, `Math.${name}`);
  try {
    return fn();
  } finally {
    for (const restore of restores.reverse()) restore();
  }
}

