const lineOfText = (text, needle) => {
  const index = text.indexOf(needle);
  return index < 0 ? 1 : text.slice(0, index).split('\n').length;
};
const readJson = (root, rel) => {
  const abs = join(root, rel);
  if (!existsSync(abs)) return { exists: false };
  const text = readFileSync(abs, 'utf8');
  try {
    return { exists: true, text, data: JSON.parse(text) };
  } catch (error) {
    return { exists: true, text, error: String(error.message).split('\n')[0] };
  }
};
const isObject = (value) => value !== null && typeof value === 'object' && !Array.isArray(value);
const isUint32 = (value) => Number.isInteger(value) && value >= 0 && value <= 0xffffffff;

/** The version the cutover table assigns to a date key. */
function route(versions, key) {
  let served = 0;
  for (const entry of versions) if (entry.from === null || entry.from <= key) served = entry.version;
  return served;
}

function shapeProblems(g, seenIds) {
  if (!isObject(g)) return ['a generator entry is not an object'];
  const problems = [];
  for (const key of REQUIRED_KEYS) if (!(key in g)) problems.push(`missing "${key}"`);
  for (const key of Object.keys(g)) if (!GENERATOR_KEYS.has(key)) problems.push(`unknown key "${key}"`);
  if ('id' in g && (typeof g.id !== 'string' || !KEBAB.test(g.id))) problems.push('"id" is not a kebab-case name');
  if (typeof g.id === 'string' && seenIds.has(g.id)) problems.push(`"id" ${g.id} is used twice`);
  for (const key of ['module', 'vectors', 'regenerate']) if (key in g && (typeof g[key] !== 'string' || g[key].trim() === '')) problems.push(`"${key}" is not a non-empty string`);
  for (const key of ['generate', 'saltExport', 'versionsExport']) if (key in g && (typeof g[key] !== 'string' || !IDENTIFIER.test(g[key]))) problems.push(`"${key}" is not an export name`);
  if ('summarize' in g && (typeof g.summarize !== 'string' || !IDENTIFIER.test(g.summarize))) problems.push('"summarize" is not an export name');
  if ('keyKind' in g && !['date', 'text'].includes(g.keyKind)) problems.push('"keyKind" is not "date" or "text"');
  if ('salt' in g && !isUint32(g.salt)) problems.push('"salt" is not an unsigned 32-bit integer');
  if ('versions' in g && (!Array.isArray(g.versions) || g.versions.length === 0 || !g.versions.every((entry) => isObject(entry) && Number.isInteger(entry.version) && (entry.from === null || typeof entry.from === 'string')))) problems.push('"versions" is not a list of { "version", "from" }');
  if ('outcome' in g && g.outcome !== null && !(isObject(g.outcome) && typeof g.outcome.file === 'string' && typeof g.outcome.versionField === 'string' && IDENTIFIER.test(g.outcome.versionField))) problems.push('"outcome" is not null or { "file", "versionField" }');
  return problems;
}

function versionTableProblems(g) {
  const problems = [];
  g.versions.forEach((entry, index) => {
    if (entry.version !== index + 1) problems.push(`entry ${index} is version ${entry.version} (versions are 1..n in order)`);
    else if (index === 0 && entry.from !== null) problems.push('version 1 must have "from": null');
    else if (index > 0 && g.keyKind === 'text' && entry.from !== null) problems.push(`version ${entry.version}: a text-keyed generator has no cutover key ("from": null; callers pass the version)`);
    else if (index > 0 && g.keyKind === 'date' && !spec.isSpecDateKey(entry.from)) problems.push(`version ${entry.version} needs a civil-date cutover key`);
    else if (index > 0 && g.keyKind === 'date' && entry.from <= (g.versions[index - 1].from ?? '')) problems.push(`version ${entry.version} starts ${entry.from}, not after version ${index}'s cutover`);
  });
  return problems;
}

