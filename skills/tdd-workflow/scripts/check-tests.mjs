const EXTRA_IGNORES = ['reports/**', '.stryker-tmp/**', 'dist-audit/**'];
const NODE_BUILTINS = ['assert', 'buffer', 'child_process', 'crypto', 'events', 'fs', 'fs/promises', 'http', 'https', 'net', 'os', 'path', 'process', 'stream', 'url', 'util', 'worker_threads', 'zlib'];
const TITLE_VERB = /^(can|[a-z]+s)\b/;
/** A declaration of runtime code (a function, a class, a function-valued const) named `name` (a regex source). */
const runtimeDeclaration = (name) => String.raw`(?:async\s+)?function\s*\*?\s*${name}\b|(?:abstract\s+)?class\s*${name}\b|const\s+${name}\s*(?::[^=\n]+)?=\s*(?:async\s*)?(?:<[^>]*>\s*)?(?:\([^)]*\)|\w+)\s*(?::[^=\n]+)?=>|const\s+${name}\s*=\s*(?:async\s+)?function\b|const\s+${name}\s*(?::[^=\n]+)?=\s*[A-Za-z_$][\w$]*\s*(?:<[^>]*>)?\(`;
const RUNTIME_EXPORT = new RegExp(String.raw`^export\s+(?:default\s+)?(?:${runtimeDeclaration(String.raw`[\w$]*`)})`, 'm');
/** export { a, b as c }: a local list (never a re-export "from" another module). */
const EXPORT_LIST = /^export\s*\{([^}]*)\}(?!\s*from\b)/gm;
const SIBLING_TESTS = ['.test.ts', '.test.tsx', '.golden.test.ts', '.android.test.ts', '.android.test.tsx'];
const DEVICE_ONLY = /^\/\/\s*device-only:(.*)$/m;
const DEVICE_ONLY_REASON = /\bcovered by\s+\S.{8,}/i;

const CHECKS = [
  { rule: 'disabled-test', re: /\b(?:it|test|describe)(?:\.concurrent)?\.(?:only|skip|failing|todo)\b|(?<![\w.$])(?:xit|xtest|xdescribe|fit|fdescribe)\s*\(/g, message: (m) => `"${m}" disables or focuses tests`, fix: 'Remove it: finish the behaviour in this slice or delete the test; skipped tests rot and focused tests hide the rest.' },
  { rule: 'test-retry', re: /\bjest\.retryTimes\s*\(/g, message: () => 'jest.retryTimes hides a flaky test', fix: 'Reproduce with --randomize --seed=<n> -i and fix the cause (shared state, real timers, time zone, unawaited promise).' },
  { rule: 'use-it', re: /(?<![\w.$])test(?:\.each\b[\s\S]{0,400}?\)\s*)?\(\s*['"`]/g, message: () => 'test(...) is used instead of it(...)', fix: 'Write it("<third-person verb> ...") so titles read as the requirement.' },
  { rule: 'component-snapshot', re: /\.(?:toMatchSnapshot|toMatchInlineSnapshot|toThrowErrorMatchingSnapshot|toThrowErrorMatchingInlineSnapshot|toMatchImageSnapshot)\s*\(/g, skip: (rel) => rel.endsWith('.golden.test.ts'), message: (m) => `${m.replace(/\s*\($/, '')} outside a *.golden.test.ts file`, fix: 'Assert roles, names and visible text; readable data snapshots belong in <unit>.golden.test.ts only.' },
  { rule: 'test-nondeterminism', re: /\bMath\.random\s*\(|\bDate\.now\s*\(|\bnew\s+Date\s*\(\s*\)|\bperformance\.now\s*\(/g, allow: (rel, match, code, layout) => isPerfTiming(rel, match, code, layout), message: (m) => `${m.replace(/\s*\($/, '(')} reads real time or randomness`, fix: 'Use the fake clock port, a fixed date string, or the seeded random-number generator.' },
  { rule: 'test-nondeterminism', re: /\bnew\s+Promise\s*(?:<[^>]*>)?\s*\(\s*(?:\(\s*[\w$]*\s*\)|[\w$]+)\s*=>\s*\{?\s*setTimeout\s*\(/g, message: () => 'a real setTimeout wait (new Promise(... => setTimeout(...)))', fix: 'Drive time with fake timers (jest.useFakeTimers(), then await jest.advanceTimersByTimeAsync(ms)) or wait on an awaited result; to let queued promises run, use the flushMicrotasks test helper.' },
];

/**
 * A perf budget test must time real work: it lives under the root test/ folder as <name>.perf.test.ts
 * and times with performance.now() from node:perf_hooks (jest-expo replaces the global one with a
 * 1 ms Date.now mock). Only that call is allowed there.
 */
function isPerfTiming(rel, match, code, layout) {
  return rel.startsWith(`${layout.testDir}/`) && rel.endsWith('.perf.test.ts') && /^performance\.now/.test(match) && /import\s*\{[^}]*\bperformance\b[^}]*\}\s*from\s*['"]node:perf_hooks['"]/.test(code);
}

/** Index just after the parenthesised group that starts at `open` (which must be "("). */
function closeParen(text, open) {
  let depth = 0;
  for (let i = open; i < text.length; i += 1) {
    const ch = text[i];
    if (ch === '"' || ch === "'" || ch === '`') {
      const end = text.indexOf(ch, i + 1);
      i = end === -1 ? text.length : end;
    } else if (ch === '(') depth += 1;
    else if (ch === ')') {
      depth -= 1;
      if (depth === 0) return i + 1;
    }
  }
  return -1;
}

function titles(code, callee) {
  const out = [];
  const plain = new RegExp(String.raw`(?<![\w.$])${callee}\s*\(\s*(['"\`])((?:\\.|(?!\1)[^\\])*)\1`, 'g');
  for (const match of code.matchAll(plain)) out.push({ index: match.index, title: match[2] });
  // it.each<[Args, Result]>(...) (a type argument list, up to two levels deep) is a table too.
  const each = new RegExp(String.raw`(?<![\w.$])${callee}\.each(?:\s*<(?:[^<>]|<(?:[^<>]|<[^<>]*>)*>)*>)?\s*\(`, 'g');
  for (const match of code.matchAll(each)) {
    const after = closeParen(code, match.index + match[0].length - 1);
    if (after === -1) continue;
    const call = /^\s*\(\s*(['"`])((?:\\.|(?!\1)[^\\])*)\1/.exec(code.slice(after));
    if (call) out.push({ index: match.index, title: call[2] });
  }
  return out;
}

const inDir = (rel, dir) => rel === dir || rel.startsWith(`${dir}/`);

function checkTestFile(context, rel, source, shown) {
  const { report, layout, importedByTests, root } = context;
  const code = maskComments(source);
  const at = (index) => lineOf(code, index);
  for (const check of CHECKS) {
    if (check.skip?.(rel)) continue;
    for (const match of code.matchAll(check.re)) {
      if (check.allow?.(rel, match[0], code, layout)) continue;
      report.problem({ file: shown, line: at(match.index), rule: check.rule, message: check.message(match[0]), fix: check.fix });
    }
  }
  for (const { index, title } of titles(code, 'it')) {
    if (!TITLE_VERB.test(title)) report.problem({ file: shown, line: at(index), rule: 'test-title-verb', message: `it("${title.slice(0, 60)}") does not start with a third-person verb or "can"`, fix: 'Start with what the unit does: "returns ...", "emits ...", "keeps ...", "shows ..." (never "should ...").' });
  }
  for (const { index, title } of titles(code, 'describe')) {
    if (/^(tests?|unit tests?|misc|stuff|specs?|all|main)$/i.test(title.trim())) report.problem({ file: shown, line: at(index), rule: 'describe-generic', message: `describe("${title}") says nothing`, fix: 'Name the outer describe after the exported unit (describe("taskUrgency")) and inner ones after the condition (describe("when ...")).' });
  }
  if (context.sourceDirs.some((dir) => inDir(rel, dir))) {
    for (const match of code.matchAll(/(?:\bfrom\s+|\bimport\s*\(\s*|\brequire\s*\(\s*)(['"])([^'"]+)\1/g)) {
      const spec = match[2];
      if (spec.startsWith('node:') || NODE_BUILTINS.includes(spec)) report.problem({ file: shown, line: at(match.index), rule: 'node-api-in-app-test', message: `imports "${spec}" in an app test (the app program has Jest types only)`, fix: `Move the test and its Node helper under the root ${layout.testDir}/ folder (${layout.testDir}/integration/<area>/), importing the unit through @/.` });
    }
  }
  if (!/\bexpect\s*\(|\bfc\.assert\s*\(|\bexpect\.assertions\s*\(/.test(code)) report.problem({ file: shown, line: 1, rule: 'test-without-assertion', message: 'the test file never calls expect( or fc.assert(', fix: 'Assert the behaviour; a test without an assertion passes whatever the code does.' });
  for (const match of code.matchAll(/(?:\bfrom\s+|\bimport\s*\(\s*|\brequire\s*\(\s*|\bjest\.(?:mock|requireActual)\s*\(\s*)(['"])([^'"]+)\1/g)) {
    const target = resolveImport(rel, match[2], { root, aliases: layout.aliases });
    if (target.kind === 'local' && target.path) importedByTests.add(target.path);
  }
}

/**
 * True when the module exports runtime code a test can run: an exported function, class or
 * function-valued const, or a local one listed in export { }. Type-only, constants-only and re-export
 * modules are not logic (the tests that use them cover them). An exported object of functions
 * (export const cases = { add: (s) => ... }) is not detected: a migration object or a reducer-case
 * table is often tested through the registry that imports it, so the coverage gate holds it instead.
 */
function hasRuntimeExport(code) {
  if (RUNTIME_EXPORT.test(code)) return true;
  for (const match of code.matchAll(EXPORT_LIST)) {
    const names = match[1].split(',').map((entry) => entry.trim()).filter((entry) => entry !== '' && !entry.startsWith('type ')).map((entry) => entry.split(/\s+as\s+/)[0].trim());
    if (names.some((name) => /^[\w$]+$/.test(name) && new RegExp(String.raw`^(?:${runtimeDeclaration(name.replace(/\$/g, '\\$'))})`, 'm').test(code))) return true;
  }
  return false;
}

function checkLogicModule(context, rel) {
  const { report, root, importedByTests, shownOf } = context;
  const source = readText(join(root, rel));
  if (source === null) return false;
  if (!hasRuntimeExport(maskComments(source))) return true;
  // A file a tool writes says so in its first 3 lines ("// GENERATED by scripts/art/build-icon-paths.ts");
  // its generator carries the test (check-test-edits exempts the same files).
  if (/GENERATED by \S/.test(source.split('\n').slice(0, 3).join('\n'))) return true;
  const deviceOnly = DEVICE_ONLY.exec(source.split('\n').slice(0, 6).join('\n'));
  if (deviceOnly) {
    if (!DEVICE_ONLY_REASON.test(deviceOnly[1])) report.problem({ file: shownOf(rel), line: lineOf(source, deviceOnly.index), rule: 'device-only-reason', message: `"${deviceOnly[0].trim().slice(0, 60)}" does not name the check that covers it`, fix: 'Write "// device-only: covered by <the e2e flow or device check that exercises it>", or better, test it through a fake or the root mock.' });
    return true;
  }
  const stem = rel.replace(/\.ts$/, '');
  if (SIBLING_TESTS.some((suffix) => existsSync(join(root, `${stem}${suffix}`))) || importedByTests.has(rel)) return true;
  report.problem({ file: shownOf(rel), line: 1, rule: 'untested-module', message: `${basename(rel)} has runtime exports but no test imports it`, fix: `Write ${basename(stem)}.test.ts next to it, starting with one failing test for its main behaviour (a Node-API test under ${context.layout.testDir}/ that imports it counts too).` });
  return true;
}

run(async () => {
  const { options, positionals } = parseArgs(process.argv.slice(2), SPEC);
  const root = requireDir(positionals[0] ?? '.', 'repo root');
  const layout = resolveLayout(root);
  const contract = readTddContract(root, layout, options.contract);
  const report = createReporter({ name: 'check-tests', json: options.json });
  const shownOf = (rel) => toPosix(relative(process.cwd(), join(root, rel))) || rel;
  const logicGlobs = options.logic?.length ? options.logic : contract.logicGlobs;
  const files = walkRepo(root, { include: ['*.ts', '*.tsx'], ignore: [...EXTRA_IGNORES, ...contract.ignore, ...(options.ignore ?? [])] });
  const context = { report, layout, root, shownOf, importedByTests: new Set(), sourceDirs: appSourceDirs(layout) };
  const routes = routeDirs(layout);
  let checked = 0;
  for (const rel of files) {
    const shown = shownOf(rel);
    if (/\.spec\.tsx?$/.test(rel) || rel.split('/').includes('__tests__')) {
      checked += 1;
      report.problem({ file: shown, line: 1, rule: 'test-file-name', message: 'test files are <unit>.test.ts(x) next to the unit', fix: 'Rename to <unit>.test.ts(x) and move it next to the unit; the Jest projects run only *.test.ts(x), *.golden.test.ts and *.sim.test.ts.' });
      continue;
    }
    if (!TEST_FILE.test(rel)) continue;
    const source = readText(join(root, rel));
    if (source === null) continue;
    checked += 1;
    if (routes.some((dir) => inDir(rel, dir))) report.problem({ file: shown, line: 1, rule: 'test-in-routes', message: `a test inside the routes folder (${routes.find((dir) => inDir(rel, dir))}/) is bundled by Expo Router as a route`, fix: 'Move it to src/features/<feature>/ (a route test is <feature>-navigation.test.tsx there) and render the route through the router helper.' });
    checkTestFile(context, rel, source, shown);
  }
  for (const rel of files) {
    if (TEST_FILE.test(rel) || !rel.endsWith('.ts') || rel.endsWith('.d.ts')) continue;
    if (!logicGlobs.some((glob) => matchGlob(rel, glob))) continue;
    if (/(^|\/)(testing|fixtures|__mocks__)\//.test(rel)) continue;
    if (checkLogicModule(context, rel)) checked += 1;
  }
  return report.finish({ checked, unit: 'test files and logic modules' });
});

