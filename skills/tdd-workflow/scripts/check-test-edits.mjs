const FORMAT = '==> commit %H%n%B%n==> diff';
const ASSERTION = /\bexpect\s*\(|\bfc\.assert\s*\(|\bexpect\.assertions\s*\(/;
// Call sites only (read with comments and string contents blanked): it.only(, describe.skip.each(, fit(, ...
// A type argument list after .each (it.each<[Args, Result]>(...), the form the skill's template writes),
// with up to two levels of nesting (Array<Record<string, number>>).
const TYPE_ARGS = String.raw`(?:\s*<(?:[^<>]|<(?:[^<>]|<[^<>]*>)*>)*>)?`;
const DISABLED = new RegExp(String.raw`\b(?:it|test|describe)(?:\.concurrent)?\.(?:only|skip|failing|todo)(?:\.each${TYPE_ARGS})?\s*[(\x60]|(?<![\w.$])(?:xit|xtest|xdescribe|fit|fdescribe)(?:\.each${TYPE_ARGS})?\s*[(\x60]|\bjest\.retryTimes\s*\(`);
const EACH_TABLE = new RegExp(String.raw`\.each${TYPE_ARGS}\s*([(\x60])`, 'g');
// A file a tool writes says so in its first lines; its generator carries the test.
const GENERATED = /GENERATED by \S/;
const GENERATED_LINES = 3;
const GIT_GENERATED = /^(Merge |Revert "|fixup! |squash! |amend! )/;
const SPEC_CHANGE = /^Spec-Change:[ \t]*(.*)$/m;
const SPEC_CHANGE_MIN = 10;
// A trailer that blames the test is editing the test to pass, never a requirement change.
const BLAMES_THE_TEST = /\b(?:tests?|assertions?|expectations?|snapshots?)\s+(?:was|were|is|are)\s+(?:wrong|broken|flaky|outdated|stale|incorrect)\b|^(?:fix(?:e[sd])?|update[sd]?|adjust(?:s|ed)?|correct(?:s|ed)?|align(?:s|ed)?)\s+(?:the\s+)?(?:tests?|assertions?|expectations?|snapshots?)\b|\bmake\s+(?:the\s+)?tests?\s+pass\b/i;
// The same marker check-tests.mjs accepts: in the first 6 lines, naming the check that covers it.
const DEVICE_ONLY = /^\/\/\s*device-only:(.*)$/m;
const HEAD_LINES = 6;

/** The code of some added lines: comments and the contents of strings and template literals blanked. */
function codeOf(lines) {
  const masked = maskComments(lines.join('\n'));
  let out = '';
  let quote = null;
  for (let i = 0; i < masked.length; i += 1) {
    const ch = masked[i];
    if (quote) {
      if (ch === '\\') {
        out += masked[i + 1] === '\n' ? ' \n' : '  ';
        i += 1;
        continue;
      }
      if (ch === quote) {
        quote = null;
        out += ch;
      } else if (ch === '\n') {
        out += ch;
        if (quote !== '`') quote = null;
      } else out += ' ';
      continue;
    }
    if (ch === '"' || ch === "'" || ch === '`') quote = ch;
    out += ch;
  }
  // A JSDoc or block comment that the hunk shows only in part: its continuation lines start with "*".
  return out.split('\n').map((line) => (/^\s*\*/.test(line) ? '' : line));
}

/** True when a module has no runtime code (types and interfaces only): nothing for a test to run. */
function isTypeOnly(text) {
  if (text === null || text === '') return false;
  const code = maskComments(text);
  const statements = code.split('\n').map((line) => line.trim()).filter(Boolean);
  return statements.every((line) => !/\bfunction\b|=>|\bclass\s|\bnew\s|\brequire\s*\(/.test(line) && !/^export\s+(?:const|let|var|default)\b|^(?:const|let|var)\s/.test(line));
}

/** True when the first lines carry a reasoned "// device-only: covered by <check>" marker. */
function isDeviceOnly(head) {
  const marker = DEVICE_ONLY.exec(head.split('\n').slice(0, HEAD_LINES).join('\n'));
  return marker !== null && /\bcovered by\s+\S.{8,}/i.test(marker[1]);
}

/** Index just after the group that opens at `open` ("(" or a backtick), or -1 when it never closes. */
function closeGroup(code, open) {
  if (code[open] === '`') {
    const end = code.indexOf('`', open + 1);
    return end === -1 ? -1 : end + 1;
  }
  let depth = 0;
  for (let i = open; i < code.length; i += 1) {
    const ch = code[i];
    if (ch === '"' || ch === "'" || ch === '`') {
      const end = code.indexOf(ch, i + 1);
      if (end === -1) return -1;
      i = end;
    } else if (ch === '(') depth += 1;
    else if (ch === ')') {
      depth -= 1;
      if (depth === 0) return i + 1;
    }
  }
  return -1;
}

/**
 * The line numbers of the rows of every it.each / test.each / describe.each table in `text` (the lines
 * strictly between the line that opens the table and the line that closes it, which holds the title).
 * A table the text opens but never closes (a diff hunk shows only part of it) runs to the end.
 */
function tableRows(text, firstLine = 1) {
  const code = maskComments(text);
  const rows = new Set();
  for (const match of code.matchAll(EACH_TABLE)) {
    const open = match.index + match[0].length - 1;
    const end = closeGroup(code, open);
    const from = lineOf(code, open) + 1;
    const to = end === -1 ? lineOf(code, code.length) : lineOf(code, end - 1) - 1;
    for (let line = from; line <= to; line += 1) rows.add(firstLine - 1 + line);
  }
  return rows;
}

/** The start of an assertion call: expect(, expect.assertions( or fc.assert(. */
const EXPECTATION_START = /\bexpect\s*\(|\bexpect\.assertions\s*\(|\bfc\.assert\s*\(/g;

/** Index just after the matcher chain that follows a call (.not, .resolves, .rejects, .toStrictEqual(...)), or -1. */
function closeChain(code, from) {
  let end = from;
  for (;;) {
    const link = /^\s*\.\s*[A-Za-z_$][\w$]*/.exec(code.slice(end, end + 200));
    if (!link) return end;
    end += link[0].length;
    const paren = /^\s*\(/.exec(code.slice(end, end + 200));
    if (paren) {
      end = closeGroup(code, end + paren[0].length - 1);
      if (end === -1) return -1;
    }
  }
}

/**
 * The line numbers of every line of every expectation in `text`: from the line that opens expect( (or
 * fc.assert() to the line that closes its matcher, so a Prettier-wrapped
 * expect(\n  planDigest(...),\n).toStrictEqual({\n  overdue: [...],\n}) counts line by line. An
 * expectation the text opens but never closes (a diff hunk shows only part of it) runs to the end.
 */
function expectationLines(text, firstLine = 1) {
  const code = maskComments(text);
  const lines = new Set();
  for (const match of code.matchAll(EXPECTATION_START)) {
    const open = match.index + match[0].length - 1;
    const group = closeGroup(code, open);
    const end = group === -1 ? -1 : closeChain(code, group);
    const from = lineOf(code, match.index);
    const to = end === -1 ? lineOf(code, code.length) : lineOf(code, end - 1);
    for (let line = from; line <= to; line += 1) lines.add(firstLine - 1 + line);
  }
  return lines;
}

/**
 * Lines `find` marks on one side of a file's diff (table rows, expectation lines): from the whole file
 * when git has it, else from what each hunk shows.
 */
function linesOf(find, file, side, text) {
  if (typeof text === 'string') return find(text);
  const found = new Set();
  for (const hunk of file.hunks) {
    const lines = hunk[side];
    if (lines.length > 0) for (const line of find(lines.map((entry) => entry.text).join('\n'), lines[0].line)) found.add(line);
  }
  return found;
}

/** Both kinds of assertion line on one side of a file's diff. */
function assertionLinesOf(file, side, text) {
  return { rows: linesOf(tableRows, file, side, text), expectations: linesOf(expectationLines, file, side, text) };
}

function git(repo, args) {
  const result = spawnSync('git', ['-C', repo, ...args], { encoding: 'utf8', maxBuffer: 256 * 1024 * 1024 });
  const why = (result.stderr || result.error?.message || '').trim().split('\n')[0];
  if (result.error || result.status !== 0) fail(`git ${args.join(' ')} failed: ${why}`, 'Run inside a git repository and pass a valid revision range.');
  return result.stdout;
}

/**
 * Where the app sits inside its git repository: "" at the top level, "mobile/" when the Expo app is a
 * subfolder of a full-stack repo (git prints paths from the top level), or null outside any work tree.
 */
function appPrefix(repo) {
  const result = spawnSync('git', ['-C', repo, 'rev-parse', '--is-inside-work-tree', '--show-prefix'], { encoding: 'utf8' });
  if (result.error || result.status !== 0) return null;
  const [inside, prefix = ''] = result.stdout.split('\n');
  return inside.trim() === 'true' ? prefix.trim() : null;
}

/**
 * The commit as the app sees it: only files inside the app folder, with paths relative to it (a file
 * moved in from outside counts as added). With no prefix the commit is unchanged.
 */
function scopedToApp(commit, prefix) {
  if (!prefix) return commit;
  const inside = (path) => path.startsWith(prefix);
  const files = commit.files.filter((file) => inside(file.path) || inside(file.oldPath)).map((file) => {
    if (!inside(file.path)) return { ...file, path: file.oldPath.slice(prefix.length), oldPath: file.oldPath.slice(prefix.length), status: 'deleted' };
    if (!inside(file.oldPath)) return { ...file, path: file.path.slice(prefix.length), oldPath: file.path.slice(prefix.length), status: 'added' };
    return { ...file, path: file.path.slice(prefix.length), oldPath: file.oldPath.slice(prefix.length) };
  });
  return { ...commit, files };
}

/** Split `git diff` / `git log -p` text into files with their added and removed lines. */
function parseDiff(text) {
  const files = [];
  let file = null;
  let oldLine = 0;
  let newLine = 0;
  for (const line of text.split('\n')) {
    const header = /^diff --git a\/(.+) b\/(.+)$/.exec(line);
    if (header) {
      file = { oldPath: header[1], path: header[2], status: 'modified', added: [], removed: [], head: new Map(), hunks: [] };
      files.push(file);
      continue;
    }
    if (!file) continue;
    if (line.startsWith('new file mode')) file.status = 'added';
    else if (line.startsWith('deleted file mode')) file.status = 'deleted';
    else if (line.startsWith('rename from ')) file.status = 'renamed';
    else if (line.startsWith('--- ') || line.startsWith('+++ ')) continue;
    else if (line.startsWith('@@')) {
      const hunk = /^@@ -(\d+)(?:,\d+)? \+(\d+)(?:,\d+)? @@/.exec(line);
      oldLine = hunk ? Number(hunk[1]) : 0;
      newLine = hunk ? Number(hunk[2]) : 0;
      file.hunks.push({ old: [], new: [] });
    } else if (line.startsWith('+')) {
      file.added.push({ text: line.slice(1), line: newLine });
      file.hunks.at(-1)?.new.push({ text: line.slice(1), line: newLine });
      if (newLine <= HEAD_LINES) file.head.set(newLine, line.slice(1));
      newLine += 1;
    } else if (line.startsWith('-')) {
      file.removed.push({ text: line.slice(1), line: oldLine });
      file.hunks.at(-1)?.old.push({ text: line.slice(1), line: oldLine });
      oldLine += 1;
    } else if (line.startsWith(' ')) {
      file.hunks.at(-1)?.old.push({ text: line.slice(1), line: oldLine });
      file.hunks.at(-1)?.new.push({ text: line.slice(1), line: newLine });
      if (newLine <= HEAD_LINES) file.head.set(newLine, line.slice(1));
      oldLine += 1;
      newLine += 1;
    }
  }
  return files;
}

function parseLog(text) {
  const commits = [];
  let current = null;
  let inDiff = false;
  const lines = text.split('\n');
  for (const line of lines) {
    const start = /^==> commit ([0-9a-f]{7,40})$/.exec(line);
    if (start) {
      current = { sha: start[1], message: [], diff: [] };
      commits.push(current);
      inDiff = false;
    } else if (current && line === '==> diff') inDiff = true;
    else if (current) (inDiff ? current.diff : current.message).push(line);
  }
  return commits.map((commit) => ({ sha: commit.sha, message: commit.message.join('\n').trim(), files: parseDiff(commit.diff.join('\n')) }));
}

/** The commit without the files every repo scan skips (installed skills, generated output) and the contract's ignores. */
function withoutIgnored(commit, ignore) {
  const skipped = (path) => isRepoScanIgnored(path) || ignore.some((glob) => matchGlob(path, glob));
  return { ...commit, files: commit.files.filter((file) => !skipped(file.path) || !skipped(file.oldPath)) };
}

// Whitespace and the trailing commas Prettier adds when it wraps a call or literal do not change an assertion.
const strip = (text) => text.replace(/\s+/g, '').replace(/,(?=[)\]}])/g, '');

/** The file's first lines at this commit: from git when a repo is at hand, else what the diff shows. */
function headOf(file, commit, readFile) {
  const text = readFile?.(commit.sha, file.path);
  if (typeof text === 'string') return text;
  const lines = [];
  for (let line = 1; line <= HEAD_LINES && file.head.has(line); line += 1) lines.push(file.head.get(line));
  return lines.join('\n');
}

// Tokens of a line for the rename rule: string and template literals, numbers, identifiers, the rest.
const TOKEN = /'(?:\\.|[^'\\])*'|"(?:\\.|[^"\\])*"|`(?:\\.|[^`\\])*`|\d[\w.]*|[A-Za-z_$][\w$]*|\S/g;
const IDENTIFIER = /^[A-Za-z_$][\w$]*$/;
// Names a rename never touches: what the assertion does (matchers, asymmetric matchers after expect.,
// the runners) and the literal keywords. toBe -> toEqual or true -> false is a changed assertion.
const MATCHER = /^(?:to[A-Z]\w*|not|resolves|rejects)$/;
const FIXED_NAMES = new Set('expect fc assert assertions property it test describe each true false null undefined NaN Infinity new typeof void await async function return this super in of instanceof'.split(' '));

/**
 * A line as the rename rule sees it: `shape` keeps literals, matchers and punctuation and replaces each
 * other identifier with a slot (whitespace and Prettier's trailing commas dropped); `names` lists the
 * identifiers in slot order.
 */
function renameShape(text) {
  const tokens = text.match(TOKEN) ?? [];
  const names = [];
  const shape = tokens.map((token, index) => {
    if (!IDENTIFIER.test(token) || FIXED_NAMES.has(token)) return token;
    const after = tokens[index - 1] === '.' ? tokens[index - 2] : null;
    if (tokens[index - 1] === '.' && (MATCHER.test(token) || after === 'expect')) return token;
    names.push(token);
    return '\u0000';
  }).join('').replace(/,(?=[)\]}])/g, '');
  return { shape, names };
}

/** Every identifier of a file's code (string contents and comments are not names). */
function identifiersOf(text) {
  return new Set((maskComments(text).match(TOKEN) ?? []).filter((token) => IDENTIFIER.test(token)));
}

/**
 * The removed assertion lines a refactor or style commit only renamed: each pairs with an added line of
 * the same shape (literals and matchers unchanged), and every renamed identifier follows ONE mapping
 * across the commit that really introduces a name: each old name is gone from the commit's new test and
 * source code (`newCodeNames`), and each new name was absent from the old version of the commit's
 * changed test and source files (`oldCodeNames`). planDigest( -> buildDigest( passes; toBe('today') ->
 * toBe('soon'), toBeGreaterThan -> toBeLessThan, a name renamed two ways, or .openCount -> .doneCount
 * when doneCount already existed (or openCount still exists) do not: that moves the assertion onto
 * another property, it renames nothing.
 */
function renamedOnly(changed, addedLines, newCodeNames, oldCodeNames) {
  const added = addedLines.map(renameShape);
  const pairings = changed.map(({ entry }) => {
    const removed = renameShape(entry.text);
    return added.filter((line) => line.shape === removed.shape && line.names.length === removed.names.length).map((line) => removed.names.map((name, index) => [name, line.names[index]]));
  });
  const mapping = new Map();
  // A name renamed two ways is no rename.
  const invalid = new Set();
  for (const options of pairings) {
    if (options.length !== 1) continue;
    for (const [from, to] of options[0]) {
      if (from === to) continue;
      if (mapping.has(from) && mapping.get(from) !== to) invalid.add(from);
      mapping.set(from, to);
    }
  }
  // A swap onto a name that already existed, or away from a name the code still has, introduces no name.
  for (const [from, to] of mapping) if (newCodeNames.has(from) || oldCodeNames.has(to)) invalid.add(from);
  const fits = (pairs) => pairs.every(([from, to]) => (from === to ? !mapping.has(from) : mapping.get(from) === to && !invalid.has(from)));
  return new Set(changed.filter((_, index) => pairings[index].some(fits)));
}

const LEADING_SEPARATORS = /^[\s:;,.()[\]–—-]+/u;

/**
 * The trailer's reason without the requirement references it opens with, so the canonical
 * "Spec-Change: TASKS-21 update snapshot" is read as "update snapshot" (and blames the test).
 */
function reasonOf(value, requirementPattern) {
  const references = [requirementPattern, DEFAULT_REQUIREMENT_REF].filter(Boolean).map((re) => new RegExp(`^(?:${re.source})`, re.flags.replace('g', '')));
  let rest = value.replace(LEADING_SEPARATORS, '');
  for (let stripped = true; stripped; ) {
    stripped = false;
    for (const re of references) {
      const match = re.exec(rest);
      if (match && match[0].length > 0) {
        rest = rest.slice(match[0].length).replace(LEADING_SEPARATORS, '');
        stripped = true;
      }
    }
  }
  return rest;
}

/** Why a Spec-Change trailer does not count, or null when it names a real requirement change. */
function specChangeProblem(value, requirementPattern) {
  if (value.length < SPEC_CHANGE_MIN) return `"Spec-Change: ${value}" is too short to say which requirement changed and how`;
  if (BLAMES_THE_TEST.test(reasonOf(value, requirementPattern))) return `"Spec-Change: ${value.slice(0, 60)}" blames the test, not a requirement`;
  if (requirementPattern && !requirementPattern.test(value)) return `"Spec-Change: ${value.slice(0, 60)}" cites no requirement ID (${requirementPattern.source})`;
  if (!requirementPattern && !DEFAULT_REQUIREMENT_REF.test(value)) return `"Spec-Change: ${value.slice(0, 60)}" names no requirement reference (a key such as TASKS-12, #41, issue 41 or spec 4.2)`;
  return null;
}

function checkSpecChange(context, commit, sha) {
  const trailer = SPEC_CHANGE.exec(commit.message);
  if (!trailer) return false;
  const value = trailer[1].trim();
  const problem = specChangeProblem(value, context.contract.requirementPattern);
  if (problem === null) return true;
  context.report.problem({ file: `${sha}:(message)`, line: 0, rule: 'spec-change-reason', message: problem, fix: 'Only a changed requirement moves an expectation: write "Spec-Change: <requirement ID or issue> <what changed>". If the test was wrong, the code is what to fix (or ask the reviewer).' });
  return false;
}

function checkRequirementQuoted(context, commit, sha, type, testFiles) {
  const pattern = context.contract.requirementPattern;
  if (!pattern || (type !== 'feat' && type !== 'fix')) return;
  for (const file of testFiles.filter((changed) => changed.status === 'added')) {
    if (file.added.some((entry) => pattern.test(entry.text))) continue;
    context.report.problem({ file: `${sha}:${file.path}`, line: 1, rule: 'requirement-not-quoted', message: `the new test quotes no requirement ID (${pattern.source})`, fix: 'Quote the requirement the first test serves in its title or a comment above it, printed from the spec, never from memory.' });
  }
}

function checkCommit(context, commit, readFile) {
  const { report, isSource } = context;
  const header = commit.message.split('\n')[0] ?? '';
  if (GIT_GENERATED.test(header)) return;
  const sha = commit.sha.slice(0, 7);
  const type = /^([a-z]+)(?:\([^)]*\))?!?:/.exec(header)?.[1] ?? '';
  const hasSpecChange = checkSpecChange(context, commit, sha);
  const testFiles = commit.files.filter((file) => TEST_FILE.test(file.path));
  const sourceFiles = commit.files.filter((file) => isSource(file.path) && file.status !== 'deleted');
  const deletedPaths = new Set(commit.files.filter((file) => file.status === 'deleted').map((file) => file.path));
  const addedBlob = strip(testFiles.flatMap((file) => file.added.map((entry) => entry.text)).join('\n'));
  // A removed line survives when the added lines still hold it, re-wrapped or not (its trailing comma
  // drops when Prettier joins it onto the closing line).
  const survives = (text) => {
    const line = strip(text);
    return addedBlob.includes(line) || (line.endsWith(',') && [')', ']', '}'].some((closer) => addedBlob.includes(`${line.slice(0, -1)}${closer}`)));
  };
  const where = (file, entry) => ({ file: `${sha}:${file.path}`, line: entry?.line ?? 0 });

  for (const file of commit.files.filter((changed) => /\.(ts|tsx|js|jsx|mjs|cjs)$/.test(changed.path))) {
    const code = codeOf(file.added.map((entry) => entry.text));
    file.added.forEach((entry, index) => {
      if (DISABLED.test(code[index] ?? '')) report.problem({ ...where(file, entry), rule: 'disabled-test-added', message: `adds "${entry.text.trim().slice(0, 70)}"`, fix: 'Finish or delete the test in this slice; never commit skipped, focused or retried tests.' });
    });
  }
  checkRequirementQuoted(context, commit, sha, type, testFiles);
  const changedAssertions = [];
  let addedAssertions = 0;
  const meaningful = (entry) => /[\w'"`]/.test(entry.text);
  for (const file of testFiles) {
    const added = file.status === 'deleted' ? { rows: new Set(), expectations: new Set() } : assertionLinesOf(file, 'new', readFile?.(commit.sha, file.path));
    addedAssertions += file.added.filter((entry) => ASSERTION.test(entry.text) || ((added.rows.has(entry.line) || added.expectations.has(entry.line)) && meaningful(entry))).length;
    if (file.status === 'added') continue;
    if (file.status === 'deleted') {
      // foo.android.test.tsx usually tests foo.tsx (the Android project runs the shared unit).
      const stem = file.path.replace(TEST_FILE, '');
      const unitGone = [stem, stem.replace(/\.android$/, '')].some((unit) => ['.ts', '.tsx'].some((extension) => deletedPaths.has(`${unit}${extension}`)));
      if (!unitGone && !hasSpecChange) report.problem({ ...where(file), rule: 'test-deleted', message: 'deletes a test file while its unit stays', fix: 'Keep the test; if the requirement removed the behaviour, delete the unit too, or add "Spec-Change: <requirement and what changed>".' });
      continue;
    }
    const old = assertionLinesOf(file, 'old', readFile?.(commit.sha === 'staged' ? 'HEAD' : `${commit.sha}^`, file.oldPath));
    const kindOf = (entry) => {
      if (ASSERTION.test(entry.text) || (old.expectations.has(entry.line) && meaningful(entry))) return 'assertion';
      return old.rows.has(entry.line) && meaningful(entry) ? 'expectation table row' : null;
    };
    for (const entry of file.removed) {
      const kind = kindOf(entry);
      if (kind !== null && !survives(entry.text)) changedAssertions.push({ file, entry, kind });
    }
  }
  if (changedAssertions.length > 0 && !hasSpecChange && (type === 'refactor' || type === 'style')) {
    // A rename refactor changes assertion lines without changing what they assert. The names are read
    // from the commit's changed test and source files: whole files from git (--range, --staged), else
    // the diff's added lines (new) and removed lines (old).
    const addedLines = testFiles.flatMap((file) => file.added.map((entry) => entry.text));
    const codeFiles = commit.files.filter((file) => TEST_FILE.test(file.path) || isSource(file.path) || isSource(file.oldPath));
    const versionOf = (sha, path, lines) => {
      const whole = readFile?.(sha, path);
      return typeof whole === 'string' ? whole : lines.map((entry) => entry.text).join('\n');
    };
    const newCode = codeFiles.filter((file) => file.status !== 'deleted').map((file) => versionOf(commit.sha, file.path, file.added));
    const oldCode = codeFiles.filter((file) => file.status !== 'added').map((file) => versionOf(commit.sha === 'staged' ? 'HEAD' : `${commit.sha}^`, file.oldPath, file.removed));
    const renamed = renamedOnly(changedAssertions, addedLines, identifiersOf(newCode.join('\n')), identifiersOf(oldCode.join('\n')));
    changedAssertions.splice(0, changedAssertions.length, ...changedAssertions.filter((item) => !renamed.has(item)));
  }
  if (changedAssertions.length > 0 && !hasSpecChange) {
    const weakens = sourceFiles.length > 0 || addedAssertions < changedAssertions.length || !['test', 'refactor', 'style'].includes(type);
    if (weakens) {
      for (const { file, entry, kind } of changedAssertions) {
        report.problem({ ...where(file, entry), rule: 'assertion-changed', message: `changes the existing ${kind} "${entry.text.trim().slice(0, 70)}"`, fix: 'Restore the assertion (or the table row) and fix the code. Only a requirement change may change an expectation, with a "Spec-Change: <requirement and what changed>" trailer.' });
      }
    }
  }
  const testedCode = sourceFiles.filter((file) => {
    const head = headOf(file, commit, readFile);
    if (isDeviceOnly(head) || GENERATED.test(head.split('\n').slice(0, GENERATED_LINES).join('\n'))) return false;
    const whole = readFile?.(commit.sha, file.path);
    const shown = typeof whole === 'string' ? whole : file.status === 'added' ? file.added.map((entry) => entry.text).join('\n') : null;
    return !isTypeOnly(shown);
  });
  if ((type === 'feat' || type === 'fix') && testedCode.length > 0 && testFiles.filter((file) => file.status !== 'deleted').length === 0) {
    report.problem({ file: `${sha}:${testedCode[0].path}`, line: 0, rule: 'code-without-test', message: `"${header.slice(0, 60)}" changes production code but no test`, fix: 'Commit the failing test and the code together (red and green in one commit). Only a thin wrapper Jest cannot load may skip it, and only with "// device-only: covered by <the check that exercises it>" in its first lines.' });
  }
}

function readCommits(options, repo) {
  const prefix = appPrefix(repo);
  if (options.log) {
    const commits = parseLog(readFileSync(requireFile(options.log, 'log file'), 'utf8'));
    // A log captured at the top level of a repo whose app is a subfolder names files from the top.
    const fromTop = prefix && commits.some((commit) => commit.files.some((file) => file.path.startsWith(prefix)));
    return { commits: fromTop ? commits.map((commit) => scopedToApp(commit, prefix)) : commits, readFile: null };
  }
  if (prefix === null) fail(`${repo} is not inside a git repository`, 'Run from the app repo root, or capture a log and pass --log <file>.');
  const readFile = (sha, path) => {
    const shown = spawnSync('git', ['-C', repo, 'show', `${sha === 'staged' ? '' : sha}:${prefix}${path}`], { encoding: 'utf8', maxBuffer: 64 * 1024 * 1024 });
    return shown.status === 0 ? shown.stdout : null;
  };
  if (options.range) return { commits: parseLog(git(repo, ['log', '--reverse', '-M', '-p', '--no-color', `--format=${FORMAT}`, options.range])).map((commit) => scopedToApp(commit, prefix)), readFile };
  const message = options.message ? readFileSync(requireFile(options.message, 'message file'), 'utf8') : '';
  const files = scopedToApp({ files: parseDiff(git(repo, ['diff', '--cached', '-M', '--no-color'])) }, prefix).files;
  if (files.length === 0) fail(prefix ? `nothing is staged inside ${prefix}` : 'nothing is staged', 'Stage the slice with git add (test and code together), then rerun.');
  return { commits: [{ sha: 'staged', message: message.trim(), files }], readFile };
}

run(async () => {
  const { options, positionals } = parseArgs(process.argv.slice(2), SPEC);
  if (positionals[0] !== undefined && options.repo !== undefined && positionals[0] !== options.repo) fail(`two repo roots given: ${positionals[0]} and --repo ${options.repo}`, 'Pass the repo root once, as the positional argument.');
  const modes = [options.range, options.log, options.staged ? 'staged' : undefined].filter(Boolean);
  if (modes.length !== 1) fail('pass exactly one of --range, --log or --staged', 'Run with --help to see the modes.');
  if (options.message && !options.staged) fail('--message works only with --staged', 'Drop --message, or check the staged change with --staged --message <file>.');
  const repo = requireDir(positionals[0] ?? options.repo ?? '.', 'repo root');
  const layout = resolveLayout(repo);
  const contract = readTddContract(repo, layout, options.contract);
  const report = createReporter({ name: 'check-test-edits', json: options.json });
  const isSource = (path) => /\.tsx?$/.test(path) && contract.sourceGlobs.some((glob) => matchGlob(path, glob)) && !TEST_FILE.test(path) && !NOT_SOURCE.test(path);
  const { commits, readFile } = readCommits(options, repo);
  if (commits.length === 0) fail('the log or range holds no commits', 'Pass a range that contains the new commits, for example main..HEAD or HEAD~3..HEAD.');
  const context = { report, contract, isSource };
  for (const commit of commits) checkCommit(context, withoutIgnored(commit, contract.ignore), readFile);
  return report.finish({ checked: commits.length, unit: 'commits' });
});
