const GRID = 24;
const GRID_MARGIN = 0.5;
const STALE_TOLERANCE = 0.2;
const REGENERATE = 'Run: node scripts/art/build-icon-paths.ts (from the app root), then rerun.';
const GENERATED = /^\/\/ GENERATED by \S*build-icon-paths\.ts/;
// Icon packages only. react-native-svg is not here: it is fine for charts and illustrations, and drawing
// UI icons with it instead of <Icon> is a review point no import scan can tell apart (icon-system.md).
// The common packages only; another icon set is caught in review (icon-system.md). A bare scope
// ('@react-native-vector-icons') matches every package in it (@react-native-vector-icons/ionicons).
const ICON_PACKAGES = [
  'react-native-vector-icons',
  '@expo/vector-icons',
  '@react-native-vector-icons',
  'expo-symbols',
  'react-native-sfsymbols',
  'lucide-react-native',
  'phosphor-react-native',
  'react-native-heroicons',
  'react-native-feather',
  '@tabler/icons-react-native',
  '@hugeicons/react-native',
  'iconsax-react-native',
  'react-native-remix-icon',
  '@fortawesome/react-native-fontawesome',
];

/** True when `pkg` is a listed package, or sits in a listed bare scope. */
function inList(list, pkg) {
  return list.some((entry) => pkg === entry || (entry.startsWith('@') && !entry.includes('/') && pkg.startsWith(`${entry}/`)));
}
const IMPORT_SPEC = /(?:\bfrom\s+|\bimport\s*\(\s*|\bimport\s+|\brequire\(\s*)['"]([^'"]+)['"]/g;
const IMAGE_EXT = /\.(png|jpe?g|gif|webp|svg|bmp|heic|avif)$/i;
// Emoji presentation only: a character that shows as an emoji by default, or any pictograph forced
// to emoji by VS16 (U+FE0F). Text-presentation symbols (↔ ‼ ✔ ♠ ♥ ☀ ⚠ ➡, © ® ™) render as ordinary
// font glyphs and pass; a ZWJ sequence is caught by its first code point.
// Literal characters only: an emoji written as an escape ('\u{1F389}', String.fromCodePoint) is not seen.
const EMOJI = /\p{Emoji_Presentation}|\p{Extended_Pictographic}\uFE0F/gu;
const NOT_APP_SOURCE = ['*.test.ts', '*.test.tsx', '*.spec.ts', '*.spec.tsx', '__tests__', '__mocks__', '__image_snapshots__', 'fixtures', '*.d.ts'];

function packageOf(spec) {
  const parts = spec.split('/');
  return spec.startsWith('@') ? parts.slice(0, 2).join('/') : parts[0];
}

function layersBox(layers) {
  const box = { minX: Infinity, minY: Infinity, maxX: -Infinity, maxY: -Infinity };
  for (const layer of layers) {
    const b = pathBounds(layer.d);
    const w = layer.op === 'stroke' ? layer.width / 2 : 0;
    box.minX = Math.min(box.minX, b.minX - w);
    box.minY = Math.min(box.minY, b.minY - w);
    box.maxX = Math.max(box.maxX, b.maxX + w);
    box.maxY = Math.max(box.maxY, b.maxY + w);
  }
  return box;
}

/** The layers file, validated; null (with a problem) when it cannot be used. */
function readLayers(report, root, file) {
  const problem = (message) => report.problem({ file, line: 1, rule: 'icon-layers-invalid', message, fix: 'Fix design/icon-layers.json (the skill\'s templates/design/icon-layers.json shows the shape; references/icon-system.md, "The grid and the layer model").' });
  let data;
  try {
    data = JSON.parse(readFileSync(join(root, file), 'utf8'));
  } catch (error) {
    problem(`not valid JSON: ${error.message}`);
    return null;
  }
  const glyphs = data?.glyphs;
  if (glyphs === null || typeof glyphs !== 'object' || Array.isArray(glyphs) || Object.keys(glyphs).length === 0) {
    problem('has no "glyphs" object with at least one icon');
    return null;
  }
  if (data.viewBox !== undefined && data.viewBox !== '0 0 24 24') problem(`viewBox is "${data.viewBox}"; icons are drawn on the 24-unit grid (0 0 24 24)`);
  let usable = true;
  for (const [name, glyph] of Object.entries(glyphs)) {
    if (!/^[a-z][a-z0-9-]*$/.test(name)) problem(`icon name "${name}" is not kebab-case`);
    const layers = glyph?.layers;
    if (!Array.isArray(layers) || layers.length === 0) {
      problem(`"${name}" has no layers`);
      usable = false;
      continue;
    }
    layers.forEach((layer, index) => {
      const where = `"${name}" layer ${index}`;
      if (typeof layer?.d !== 'string' || layer.d.trim() === '') {
        problem(`${where} has no path data "d"`);
        usable = false;
      } else if (layer.op === 'stroke') {
        if (typeof layer.width !== 'number' || layer.width <= 0) problem(`${where} is a stroke without a positive width`);
        if (!['round', 'butt'].includes(layer.cap)) problem(`${where} has cap "${layer.cap}"; use round or butt`);
      } else if (layer.op === 'fill') {
        if (!['nonzero', 'evenodd'].includes(layer.fillRule)) problem(`${where} has fillRule "${layer.fillRule}"; use nonzero or evenodd`);
      } else {
        problem(`${where} has op "${layer.op}"; use stroke or fill`);
        usable = false;
      }
    });
  }
  const directional = data.directional ?? [];
  if (!Array.isArray(directional) || directional.some((name) => typeof name !== 'string')) {
    problem('"directional" must be a list of icon names');
  } else {
    for (const name of directional) if (!(name in glyphs)) problem(`directional icon "${name}" is not a glyph of the set`);
  }
  return usable ? { glyphs, directional: Array.isArray(directional) ? directional : [] } : null;
}

function checkPath(report, file, name, d, layers, line = 1) {
  let box;
  try {
    box = pathBounds(d);
  } catch (error) {
    report.problem({ file, line, rule: 'icon-path-syntax', message: `"${name}": ${error.message}`, fix: REGENERATE });
    return;
  }
  if (box.minX < -GRID_MARGIN || box.minY < -GRID_MARGIN || box.maxX > GRID + GRID_MARGIN || box.maxY > GRID + GRID_MARGIN) {
    report.problem({ file, line, rule: 'icon-path-grid', message: `"${name}" spans ${box.minX.toFixed(1)},${box.minY.toFixed(1)} to ${box.maxX.toFixed(1)},${box.maxY.toFixed(1)}, outside the 24 grid`, fix: 'Redraw the icon layers inside 0..24, then regenerate.' });
  }
  if (!layers) return;
  let want;
  try {
    want = layersBox(layers);
  } catch {
    return; // A layer with bad path data cannot be compared; build-icon-paths.ts rejects it too.
  }
  const off = Math.max(Math.abs(box.minX - want.minX), Math.abs(box.minY - want.minY), Math.abs(box.maxX - want.maxX), Math.abs(box.maxY - want.maxY));
  if (off > STALE_TOLERANCE) {
    report.problem({ file, line, rule: 'icon-path-stale', message: `"${name}" is ${off.toFixed(2)} units off its layers (a stale or swapped path)`, fix: REGENERATE });
    return;
  }
  // The same box is not the same shape: sample both on a grid and compare what they cover.
  const { mismatched, judged, example } = compareIconCoverage(d, layers);
  if (mismatched > 0) {
    const where = `${example.x},${example.y} is ${example.generated ? 'drawn but not in the layers' : 'in the layers but not drawn'}`;
    report.problem({ file, line, rule: 'icon-path-stale', message: `"${name}" covers ${mismatched} of ${judged} sample points differently from its layers (${where})`, fix: REGENERATE });
  }
}

/** The line of an ICON_PATHS entry (`name:` or `'name':`), or 1. */
function entryLine(source, name) {
  const match = new RegExp(`^\\s*['"]?${name.replace(/[-]/g, '\\-')}['"]?\\s*:`, 'm').exec(source);
  return match ? lineOf(source, match.index) : 1;
}

function sameNames(a, b) {
  return a.length === b.length && [...a].sort().every((name, i) => name === [...b].sort()[i]);
}

async function checkIconSet(report, root, { setFile, layersFile }) {
  const hasSet = existsSync(join(root, setFile));
  const hasLayers = existsSync(join(root, layersFile));
  if (!hasSet && !hasLayers) {
    report.note(`no icon set yet (${setFile} and ${layersFile} are absent): the icon rules apply once either exists; the source bans ran`);
    return 0;
  }
  if (!hasLayers) {
    report.problem({ file: layersFile, rule: 'icon-layers-missing', message: 'the icon set exists but its source layers do not, so nobody can change an icon without hand-editing paths', fix: 'Copy templates/design/icon-layers.json from this skill and put every icon\'s layers in it (references/icon-system.md).' });
  }
  const layers = hasLayers ? readLayers(report, root, layersFile) : null;
  if (!hasSet) {
    report.problem({ file: setFile, rule: 'icon-paths-missing', message: 'the layers exist but the generated icon set does not', fix: REGENERATE });
    return 1;
  }
  const source = readFileSync(join(root, setFile), 'utf8');
  if (!source.split('\n').slice(0, 3).some((line) => GENERATED.test(line))) {
    report.problem({ file: setFile, line: 1, rule: 'generated-header', message: 'lacks "// GENERATED by scripts/art/build-icon-paths.ts" in its first 3 lines (hand-edited, or the line was dropped)', fix: `${REGENERATE} The file is written only by build-icon-paths.ts; test-edit checks exempt generated files by that line.` });
  }
  let module;
  try {
    module = await enableAppImports(root).load(setFile);
  } catch (error) {
    report.problem({ file: setFile, line: 1, rule: 'icon-module-load', message: errorText(error).split('\n')[0], fix: `Keep icon-paths.ts plain data with no imports. ${REGENERATE}` });
    return 1;
  }
  const paths = module.ICON_PATHS;
  if (paths === null || typeof paths !== 'object') {
    report.problem({ file: setFile, line: 1, rule: 'icon-module-load', message: 'ICON_PATHS is not exported', fix: REGENERATE });
    return 1;
  }
  const names = Object.keys(paths);
  if (layers) {
    for (const name of Object.keys(layers.glyphs)) {
      if (!names.includes(name)) report.problem({ file: setFile, line: lineOf(source, Math.max(0, source.indexOf('ICON_PATHS'))), rule: 'icon-set', message: `icon "${name}" is in the layers but not in ICON_PATHS`, fix: REGENERATE });
    }
    for (const name of names) {
      if (!(name in layers.glyphs)) report.problem({ file: setFile, line: entryLine(source, name), rule: 'icon-set', message: `icon "${name}" has no layers in ${layersFile}`, fix: 'Add its layers to the layers file (references/icon-system.md, "Adding or changing an icon"), then regenerate; never add a path by hand.' });
    }
    const declared = module.DIRECTIONAL_ICONS ? [...module.DIRECTIONAL_ICONS] : [];
    if (!sameNames(declared, layers.directional)) {
      const at = source.indexOf('DIRECTIONAL_ICONS');
      report.problem({ file: setFile, line: at < 0 ? 1 : lineOf(source, at), rule: 'icon-set', message: `DIRECTIONAL_ICONS [${declared.join(', ')}] differs from the layers' directional list [${layers.directional.join(', ')}]`, fix: REGENERATE });
    }
  }
  for (const name of names) {
    if (typeof paths[name] !== 'string') {
      report.problem({ file: setFile, line: entryLine(source, name), rule: 'icon-path-syntax', message: `"${name}" is not a path string`, fix: REGENERATE });
      continue;
    }
    checkPath(report, setFile, name, paths[name], layers?.glyphs[name]?.layers, entryLine(source, name));
  }
  return 1;
}

/** Repo path of a relative or aliased image import (tsconfig paths, e.g. @/* or @/assets/*), for the allow-list. */
function importTarget(file, spec, layout) {
  if (spec.startsWith('.')) return posix.normalize(posix.join(posix.dirname(file), spec));
  const candidates = resolveAlias(spec, layout.aliases ?? []);
  if (candidates && candidates.length > 0) return posix.normalize(toPosix(candidates[0]));
  if (spec.startsWith('@/')) return posix.join(layout.srcDir, spec.slice(2));
  return spec;
}

function checkSources(report, root, { layout, contract }) {
  const { srcDir } = layout;
  const allowedImage = (rel) => contract.allowImages.some((glob) => matchGlob(rel, glob));
  const files = walkRepo(root, { ignore: NOT_APP_SOURCE }).filter((rel) => rel.startsWith(`${srcDir}/`));
  for (const file of files) {
    if (IMAGE_EXT.test(file)) {
      if (!allowedImage(file)) report.problem({ file, rule: 'no-image-file', message: 'image file in app source', fix: 'Draw it in code (an icon in design/icon-layers.json, or a Picture from layer data). A real photo goes into contracts/app-art.json icons.allowImages.' });
      continue;
    }
    if (!/\.(tsx?|jsx?|json)$/.test(file)) continue;
    const source = readFileSync(join(root, file), 'utf8');
    const text = file.endsWith('.json') ? source : maskComments(source);
    if (!file.endsWith('.json')) {
      for (const match of text.matchAll(IMPORT_SPEC)) {
        const spec = match[1];
        const pkg = packageOf(spec);
        if (inList(ICON_PACKAGES, pkg) && !inList(contract.allowPackages, pkg)) {
          report.problem({ file, line: lineOf(text, match.index), rule: 'no-icon-library', message: `${pkg} draws icons outside the app's icon set`, fix: 'Use <Icon name="..."> from src/ui/icons (one Skia path per icon, rasterized once). A package chosen on purpose goes into contracts/app-art.json icons.allowPackages.' });
        }
        if (IMAGE_EXT.test(spec) && !allowedImage(importTarget(file, spec, layout))) {
          report.problem({ file, line: lineOf(text, match.index), rule: 'no-image-file', message: `image import "${spec}"`, fix: 'Draw it in code; the app icon and splash PNGs are named only by the app config. A real photo goes into contracts/app-art.json icons.allowImages.' });
        }
      }
    }
    const emojiLines = new Set();
    for (const emoji of text.matchAll(EMOJI)) {
      const line = lineOf(text, emoji.index);
      if (emojiLines.has(line)) continue;
      emojiLines.add(line);
      report.problem({ file, line, rule: 'no-emoji', message: `emoji "${emoji[0]}"`, fix: 'Use an <Icon> next to the text, or remove it: emoji render differently on every OS version and are read aloud by name.' });
    }
  }
  return files.length;
}

/** One Expo app: its own folder is the root its source, contract and icon set are read from. */
async function checkApp(root, options, report) {
  const layout = resolveLayout(root);
  const srcDir = layout.srcDir;
  requireDir(join(root, srcDir), 'app source folder');
  const contract = readArtContract(root, layout.contractsDir, options.contract);
  const setFile = toPosix(options['icon-set'] ?? posix.join(layout.uiDir, 'icons', 'icon-paths.ts'));
  const layersFile = toPosix(options.layers ?? 'design/icon-layers.json');
  const sets = await checkIconSet(report, root, { setFile, layersFile });
  const files = checkSources(report, root, { layout, contract });
  return { checked: files + sets };
}

run(async () => {
  const { options, positionals } = parseArgs(process.argv.slice(2), SPEC);
  const root = requireDir(positionals[0] ?? '.', 'app root');
  const report = createReporter({ name: 'check-icons', json: options.json });
  const result = await forEachExpoApp(root, report, (appRoot, appReport) => checkApp(appRoot, options, appReport));
  if (result.notApplicable !== null) return report.notApplicable(result.notApplicable);
  return report.finish({ checked: result.checked, unit: 'source files and icon sets' });
});
