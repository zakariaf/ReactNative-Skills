#!/usr/bin/env node
// check-icons.mjs: proves an Expo app draws its UI icons in code: the icon set (src/ui/icons/icon-paths.ts)
// is generated from its source layers (design/icon-layers.json), holds exactly the layers' icons and
// directional names, and every path is valid, on the 24 grid and in step with its layers; and no app
// source draws UI with an icon font or vector-icon package, an emoji, or an image file.
// Run: node ${CLAUDE_SKILL_DIR}/scripts/check-icons.mjs [app-root] [options]

import { existsSync, readFileSync } from 'node:fs';
import { join, posix } from 'node:path';

import { createReporter, lineOf, maskComments, matchGlob, parseArgs, requireDir, resolveAlias, resolveLayout, run, toPosix, walkRepo } from './check-lib.mjs';
import { forEachExpoApp } from './lib/expo-apps.mjs';
import { readArtContract } from './lib/art-contract.mjs';
import { enableAppImports, errorText } from './lib/app-modules.mjs';
import { compareIconCoverage } from './lib/icon-coverage.mjs';
import { pathBounds } from './lib/svg-path.mjs';

