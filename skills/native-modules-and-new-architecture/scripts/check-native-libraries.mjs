#!/usr/bin/env node
// check-native-libraries.mjs: checks that every native dependency of the app runs on the New
// Architecture natively (an Expo module, or codegenConfig for a Turbo Module or Fabric component), or
// that its use through React Native's interop layer is a recorded decision with a recheck date in
// contracts/native-libraries.json; and that expo-doctor's React Native Directory check stays on, with
// every exclusion recorded. Reads the installed packages (node_modules, found the way Node finds
// them: the app's folder, then each ancestor up to the repo root), so run it after npm ci.
// Zero dependencies (node: built-ins), Node 22+.
import { existsSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';

import { createReporter, fail, parseArgs, resolveLayout, run } from './check-lib.mjs';
import { NATIVE_KINDS, classifyPackage, parseJson, readMaybe } from './lib/native-scan.mjs';

const SPEC = {
  name: 'check-native-libraries',
  summary: 'Checks that native dependencies run on the New Architecture natively, or are recorded decisions.',
  usage: '[repo-root] [options]',
  options: {
    contract: { type: 'string', value: 'file', help: 'The decisions file (default: <contractsDir>/native-libraries.json)' },
    today: { type: 'string', value: 'YYYY-MM-DD', help: 'The date recheckBy is compared with (default: today, local time)' },
    json: { type: 'boolean', help: 'Also print the problems as JSON' },
  },
  positionals: { min: 0, max: 1 },
  details: [
    'Classification of an installed package (node_modules/<name>, resolved upward like Node):',
    '  expo-module   expo-module.config.json: New Architecture by construction',
    '  new           package.json codegenConfig: a Turbo Module or Fabric component',
    '  nitro         nitro.json, or react-native-nitro-modules in dependencies/peerDependencies: a Nitro',
    '                module (JSI hybrid objects generated by nitrogen; New Architecture only)',
    '  interop       native code (a podspec, android/build.gradle) without any of these: legacy architecture',
    '                code that React Native 0.86 runs only through its interop layers',
    '  js            no native code (not checked)',
    'Rules:',
    '  library-legacy    a dependency (package.json "dependencies") classified interop has no entry in the',
    '                    decisions file; a devDependency classified interop is a note (test tooling)',
    '  library-entry     an entry lacks architecture/decision/reason/evidence/recheckBy, has an unknown value,',
    '                    or says "replace" without replaceWith',
    '  library-stale     an entry names a package that is not a direct dependency, ships no native code, or',
    '                    now runs on the New Architecture natively (delete the entry)',
    '  library-recheck   an entry\'s recheckBy date has passed',
    '  doctor-check      package.json turns expo-doctor\'s React Native Directory check off, or excludes a',
    '                    package without an entry (or with a regex, which hides future packages too)',
    'Transitive native dependencies on the interop layer are printed as notes: their parent owns them.',
    'In a workspace, run it per app (the folder with the app\'s package.json): hoisted packages are found in',
    'the ancestor node_modules folders up to the repo root (the first folder with .git or "workspaces").',
    'Not applicable when react-native is not a dependency in package.json.',
  ].join('\n'),
};

const PLATFORM_PACKAGES = new Set(['react-native', 'react', 'react-dom', 'react-native-web']);
const ENTRY_KEYS = ['architecture', 'decision', 'reason', 'evidence', 'recheckBy'];
const DATE = /^\d{4}-\d{2}-\d{2}$/;

function localToday() {
  const now = new Date();
  const pad = (n) => String(n).padStart(2, '0');
  return `${now.getFullYear()}-${pad(now.getMonth() + 1)}-${pad(now.getDate())}`;
}

function lineOfKey(text, key) {
  const index = text.indexOf(`"${key}"`);
  if (index === -1) return 1;
  let line = 1;
  for (let i = 0; i < index; i += 1) if (text.charCodeAt(i) === 10) line += 1;
  return line;
}

/**
 * The folders whose node_modules Node searches from `root`: root, then each ancestor up to and
 * including the repo root (the first folder holding .git, or a package.json with "workspaces"), or up
 * to the file-system root when there is none.
 */
function searchFolders(root) {
  const out = [];
  let dir = resolve(root);
  for (;;) {
    out.push(dir);
    const manifest = parseJson(readMaybe(join(dir, 'package.json')) ?? 'null').value;
    const isTop = existsSync(join(dir, '.git')) || (manifest && typeof manifest === 'object' && manifest.workspaces !== undefined);
    const parent = dirname(dir);
    if (isTop || parent === dir) return out;
    dir = parent;
  }
}

/** The installed folder of package `name` as seen from `fromDir` (Node's upward search), or null. */
function resolvePackage(name, fromDir, top) {
  const ancestors = [];
  let dir = fromDir;
  for (;;) {
    ancestors.push(dir);
    if (dir === top) break;
    const parent = dirname(dir);
    if (parent === dir) break;
    dir = parent;
  }
  for (const folder of ancestors) {
    if (folder.endsWith('/node_modules') || folder.endsWith('\\node_modules')) continue;
    const candidate = join(folder, 'node_modules', name);
    if (existsSync(join(candidate, 'package.json'))) return candidate;
  }
  return null;
}

/** Dependency names a package's manifest makes Node install beside it (optional peers excluded). */
function childNames(manifest) {
  const peersMeta = manifest.peerDependenciesMeta ?? {};
  const peers = Object.keys(manifest.peerDependencies ?? {}).filter((name) => peersMeta[name]?.optional !== true);
  return [...new Set([...Object.keys(manifest.dependencies ?? {}), ...Object.keys(manifest.optionalDependencies ?? {}), ...peers])];
}

async function main() {
  const { options, positionals } = parseArgs(process.argv.slice(2), SPEC);
  const root = positionals[0] ?? '.';
  if (!existsSync(root)) fail(`repo root ${root} does not exist`, 'Pass the app repo root (the folder with package.json).');
  const manifestText = readMaybe(join(root, 'package.json'));
  if (manifestText === null) fail('nothing to check: no package.json in the repo root', 'Run from the app repo root, or pass it as the first argument.');
  const parsed = parseJson(manifestText);
  if (parsed.error) fail(`package.json does not parse: ${parsed.error}`, 'Fix package.json.');
  const manifest = parsed.value;
  const today = options.today ?? localToday();
  if (!DATE.test(today)) fail(`--today ${today} is not YYYY-MM-DD`, 'Pass a date such as --today 2026-10-14.');
  const report = createReporter({ name: SPEC.name, json: options.json });
  const runtime = { ...manifest.optionalDependencies, ...manifest.dependencies };
  const direct = { ...manifest.devDependencies, ...runtime };
  if (!direct['react-native']) return report.notApplicable('react-native is not a dependency in package.json');
  const folders = searchFolders(root);
  if (!folders.some((dir) => existsSync(join(dir, 'node_modules')))) fail('nothing to check: node_modules is missing (in the app and every folder up to the repo root), so the installed packages cannot be classified', 'Install first (npm ci), then rerun.');
  const top = folders[folders.length - 1];

  const layout = resolveLayout(root);
  const contractRel = options.contract ?? `${layout.contractsDir}/native-libraries.json`;
  const contractText = readMaybe(join(root, contractRel));
  let libraries = {};
  if (contractText !== null) {
    const contract = parseJson(contractText);
    if (contract.error || !contract.value || typeof contract.value !== 'object') fail(`${contractRel} does not parse${contract.error ? `: ${contract.error}` : ''}`, 'Write valid JSON: { "libraries": { ... } } (templates/contracts/native-libraries.json).');
    if (contract.value.libraries !== undefined && (typeof contract.value.libraries !== 'object' || Array.isArray(contract.value.libraries) || contract.value.libraries === null)) fail(`${contractRel}: "libraries" must be an object keyed by package name`, 'Write { "libraries": { "<package>": { ... } } }.');
    libraries = contract.value.libraries ?? {};
  }
  const add = (file, line, rule, message, fix) => report.problem({ file, line, rule, message, fix });
  const appDir = resolve(root);
  const classes = new Map();
  /** Classifies a package installed at `dir` (null: not installed), memoised by folder. */
  const classAt = (dir) => {
    if (dir === null) return { kind: 'missing', manifest: null };
    if (!classes.has(dir)) classes.set(dir, classifyPackage(dir));
    return classes.get(dir);
  };
  const classOf = (name) => classAt(resolvePackage(name, appDir, top));

  // ---- direct dependencies -------------------------------------------------------------------
  let checked = 0;
  for (const name of Object.keys(direct).sort()) {
    if (PLATFORM_PACKAGES.has(name)) continue;
    const info = classOf(name);
    if (info.kind === 'missing') continue; // not installed: npm ci reports it, not this check
    checked += 1;
    const entry = libraries[name];
    if (info.kind === 'interop' && entry === undefined && !(name in runtime)) {
      report.note(`note: devDependency ${name} ${info.manifest.version ?? ''} ships native code without an Expo module config, codegenConfig or a Nitro marker: not checked as test tooling (Expo autolinking also links top-level devDependencies, so a runtime module belongs in "dependencies")`.replace(/\s+:/, ':'));
    } else if (info.kind === 'interop' && entry === undefined) {
      add('package.json', lineOfKey(manifestText, name), 'library-legacy', `${name} ${info.manifest.version ?? ''} ships native code without an Expo module config, codegenConfig or a Nitro marker: it is legacy architecture code that React Native runs only through the interop layer`.replace(/\s+:/, ':'), `Prefer a New Architecture alternative (an Expo SDK package, a maintained fork, or a local Expo module). If the app keeps it, record the decision in ${contractRel} with reason, evidence (React Native Directory, the screens tested on iOS and Android) and a recheckBy date.`);
    }
  }

  // ---- the decisions file --------------------------------------------------------------------
  const file = contractRel;
  for (const [name, entry] of Object.entries(libraries)) {
    const line = contractText ? lineOfKey(contractText, name) : 1;
    if (!entry || typeof entry !== 'object' || Array.isArray(entry)) {
      add(file, line, 'library-entry', `the entry for ${name} is not an object`, `Write { "architecture": "interop", "decision": "keep", "reason": "...", "evidence": "...", "recheckBy": "YYYY-MM-DD" }.`);
      continue;
    }
    const missing = ENTRY_KEYS.filter((key) => typeof entry[key] !== 'string' || entry[key].trim().length === 0);
    if (missing.length > 0) add(file, line, 'library-entry', `the entry for ${name} lacks ${missing.join(', ')}`, 'Every decision states architecture, decision, reason, evidence and recheckBy.');
    if (entry.architecture !== undefined && !['interop', 'new'].includes(entry.architecture)) add(file, line, 'library-entry', `${name}: architecture "${String(entry.architecture)}" is neither "interop" nor "new"`, 'Use "interop" (runs through the interop layer) or "new" (the classification is wrong, with evidence).');
    if (entry.decision !== undefined && !['keep', 'replace'].includes(entry.decision)) add(file, line, 'library-entry', `${name}: decision "${String(entry.decision)}" is neither "keep" nor "replace"`, 'Use "keep" or "replace".');
    if (entry.decision === 'replace' && (typeof entry.replaceWith !== 'string' || entry.replaceWith.trim() === '')) add(file, line, 'library-entry', `${name}: decision "replace" names no replaceWith`, 'Name the package or local module that replaces it in "replaceWith".');
    if (typeof entry.recheckBy === 'string' && entry.recheckBy.trim() !== '') {
      if (!DATE.test(entry.recheckBy) || Number.isNaN(Date.parse(`${entry.recheckBy}T00:00:00Z`))) add(file, line, 'library-entry', `${name}: recheckBy "${entry.recheckBy}" is not a YYYY-MM-DD date`, 'Write the date as YYYY-MM-DD.');
      else if (entry.recheckBy < today) add(file, line, 'library-recheck', `${name}: recheckBy ${entry.recheckBy} has passed (today ${today})`, 'Recheck the library (React Native Directory, its changelog, the app\'s screens on both platforms), then update the evidence and move recheckBy, or replace the library.');
    }
    if (!(name in direct)) {
      add(file, line, 'library-stale', `${name} has a decision but is not a direct dependency of the app`, 'Delete the entry (the package left), or fix its name.');
      continue;
    }
    const info = classOf(name);
    if (info.kind === 'js') add(file, line, 'library-stale', `${name} ships no native code, so there is no architecture decision to record`, 'Delete the entry.');
    else if (NATIVE_KINDS.has(info.kind) && entry.architecture !== 'new') add(file, line, 'library-stale', `${name} ${info.manifest?.version ?? ''} now runs on the New Architecture natively (${{ 'expo-module': 'an Expo module', new: 'codegenConfig', nitro: 'a Nitro module' }[info.kind]})`.replace(/\s+\(/, ' ('), 'Delete the entry: the interop decision no longer applies.');
  }

  // ---- expo-doctor's React Native Directory check --------------------------------------------
  const directoryCheck = manifest.expo?.doctor?.reactNativeDirectoryCheck;
  if (directoryCheck && typeof directoryCheck === 'object') {
    if (directoryCheck.enabled === false) add('package.json', lineOfKey(manifestText, 'reactNativeDirectoryCheck'), 'doctor-check', 'expo.doctor.reactNativeDirectoryCheck.enabled is false: npx expo-doctor no longer flags libraries that are unmaintained or untested on the New Architecture', 'Remove "enabled": false; exclude single packages with a recorded decision instead.');
    for (const excluded of Array.isArray(directoryCheck.exclude) ? directoryCheck.exclude : []) {
      if (typeof excluded !== 'string') continue;
      if (excluded.startsWith('/')) add('package.json', lineOfKey(manifestText, 'exclude'), 'doctor-check', `expo-doctor excludes the pattern ${excluded}, which also hides every future package it matches`, 'Exclude exact package names, each with an entry in the decisions file.');
      else if (!(excluded in libraries)) add('package.json', lineOfKey(manifestText, 'exclude'), 'doctor-check', `expo-doctor excludes ${excluded} from the React Native Directory check without a recorded decision`, `Add an entry for ${excluded} to ${contractRel} (reason, evidence, recheckBy), or drop the exclusion.`);
    }
  }

  // ---- transitive native dependencies on the interop layer ----------------------------------
  // Walks the installed tree from each runtime dependency, resolving every child from its parent's
  // folder (so nested and hoisted copies both count), to the depth Expo autolinking scans (9).
  const seen = new Set([appDir]);
  const noted = new Set();
  let level = Object.keys(runtime).sort().filter((name) => !PLATFORM_PACKAGES.has(name)).map((name) => ({ dir: resolvePackage(name, appDir, top), parent: name }));
  for (let depth = 0; depth < 9 && level.length > 0; depth += 1) {
    const next = [];
    for (const { dir, parent } of level) {
      if (dir === null || seen.has(dir)) continue;
      seen.add(dir);
      const info = classAt(dir);
      if (!info.manifest) continue;
      const name = info.manifest.name;
      if (depth > 0 && info.kind === 'interop' && !(name in direct) && !noted.has(name)) {
        noted.add(name);
        report.note(`note: ${name} ${info.manifest.version ?? ''} runs through the interop layer (installed through ${parent}; its parent owns that choice)`.replace(/\s+\(/, ' ('));
      }
      for (const child of childNames(info.manifest)) {
        if (!PLATFORM_PACKAGES.has(child)) next.push({ dir: resolvePackage(child, dir, top), parent });
      }
    }
    level = next;
  }

  return report.finish({ checked: Math.max(checked, Object.keys(libraries).length), unit: 'direct dependencies' });
}

run(main);
