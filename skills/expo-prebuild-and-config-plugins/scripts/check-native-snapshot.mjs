// check-native-snapshot.mjs: keeps a reviewable picture of the native config that prebuild derives
// from app.config.ts and its plugins. ios/ and android/ are git-ignored under Continuous Native
// Generation, so a pull request never shows that a dependency upgrade added a permission or an
// entitlement. This script runs npx expo config --type introspect (Info.plist, entitlements,
// Podfile properties, AndroidManifest, gradle.properties, strings, with every plugin applied, the
// auto-applied ones included), normalizes it, and compares it with the committed
// contracts/native-config.json; --write regenerates the file after a deliberate change.
// Zero dependencies (node: built-ins and check-lib only).
import { spawnSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';

import { createReporter, parseArgs, readWorkspaces, requireDir, resolveLayout, run, UsageError } from './check-lib.mjs';
import { isDir, isFile, readJsonFile, relPath, STRIPPED_ENV } from './lib/cng-scan.mjs';

const SPEC = {
  name: 'check-native-snapshot',
  summary: 'Compares the native config prebuild would write (npx expo config --type introspect, normalized) with the committed contracts/native-config.json, so every native change shows up in review; --write regenerates the snapshot.',
  usage: '[repo-root] [options]',
  options: {
    'app-dir': { type: 'string', value: 'dir', help: 'Folder that holds app.config.ts, relative to the repo root (default: the root, or the one workspace with an app config)' },
    snapshot: { type: 'string', value: 'file', help: 'The snapshot file, relative to the repo root (default: <contracts>/native-config.json)' },
    from: { type: 'string', value: 'file', help: 'Read a saved introspection (npx expo config --type introspect --json > file) instead of running Expo' },
    variant: { type: 'string', value: 'name', help: 'APP_VARIANT=EXPO_PUBLIC_APP_VARIANT for the introspection (default: production when app.config.ts reads APP_VARIANT)' },
    env: { type: 'string', multiple: true, value: 'KEY=VALUE', help: 'Extra environment for the introspection' },
    write: { type: 'boolean', help: 'Write the snapshot instead of comparing (after reviewing the change)' },
    json: { type: 'boolean', help: 'Also print the problems as JSON' },
  },
  positionals: { min: 0, max: 1 },
  details: [
    'Rules:',
    '  native-snapshot  the snapshot exists, parses, and was written for the same variant',
    '  native-drift     the introspected native config equals the snapshot; each difference is one line (added, removed, changed)',
    'The snapshot keeps: iOS Info.plist (without the two version keys), entitlements, Expo.plist and Podfile properties;',
    'Android permissions, blocked permissions, features, queries, application attributes, components with their',
    'intent filters, meta-data, gradle.properties and strings. Colors, styles and the splash storyboard are left out.',
    'Library manifests merged by Gradle at build time are not in it (check the merged manifest of a build for those).',
    'NOT APPLICABLE when package.json has no expo dependency.',
    'Bad input (exit 2): no app config, Expo not installed (npm ci, or pass --from), an unreadable --from file.',
  ].join('\n'),
};

const CONFIGS = ['app.config.ts', 'app.config.mts', 'app.config.cts', 'app.config.mjs', 'app.config.cjs', 'app.config.js', 'app.config.json', 'app.json'];
const VERSION_KEYS = ['CFBundleShortVersionString', 'CFBundleVersion'];
const COMMENT = 'Generated by check-native-snapshot.mjs --write (expo-prebuild-and-config-plugins): the native config npx expo prebuild derives from app.config.ts and its config plugins (npx expo config --type introspect). Review its diff like code; regenerate with --write only after a deliberate change.';

async function main() {
  const { options, positionals } = parseArgs(process.argv.slice(2), SPEC);
  const root = requireDir(resolve(positionals[0] ?? '.'), 'repo root');
  const layout = resolveLayout(root);
  const appDir = requireDir(resolve(root, options['app-dir'] ?? findAppDir(root)), 'app folder');
  const report = createReporter({ name: 'check-native-snapshot', json: options.json });
  const manifestPath = join(appDir, 'package.json');
  if (!isFile(manifestPath)) throw new UsageError(`nothing to check: no package.json in ${relPath(root, appDir) || '.'}`, 'Run it from the app root, or pass the repo root and --app-dir <dir>.');
  const manifest = readJsonFile(manifestPath, relPath(root, manifestPath));
  if (!('expo' in { ...manifest.devDependencies, ...manifest.dependencies })) return report.notApplicable(`expo is not a dependency in ${relPath(root, manifestPath)}`);
  const configName = CONFIGS.find((name) => isFile(join(appDir, name)));
  if (!configName) throw new UsageError(`nothing to check: no app config in ${relPath(root, appDir) || '.'}`, 'Run it from the app root, or pass the repo root and --app-dir <dir>.');

  const variant = options.variant ?? (/\bAPP_VARIANT\b/.test(readFileSync(join(appDir, configName), 'utf8')) ? 'production' : null);
  const introspection = options.from ? readFrom(root, options.from) : introspect(appDir, variant, options.env);
  const current = normalize(introspection, variant);
  const snapshotRel = options.snapshot ?? relPath(root, join(root, layout.contractsDir, 'native-config.json'));
  const snapshotPath = join(root, snapshotRel);

  if (options.write) {
    writeFileSync(snapshotPath, `${JSON.stringify(current, null, 2)}\n`);
    const formatted = formatWithPrettier(root, appDir, snapshotPath);
    report.note(`wrote ${snapshotRel} (${variant === null ? 'no variant' : `APP_VARIANT=${variant}`}): review its diff, then commit it with the change that caused it`);
    if (!formatted) report.note(`note: Prettier is not installed here; run it on ${snapshotRel} before committing (the comparison ignores formatting)`);
    return report.finish({ checked: 1, unit: 'snapshots' });
  }
  if (!isFile(snapshotPath)) {
    report.problem({ file: snapshotRel, line: 1, rule: 'native-snapshot', message: 'no native-config snapshot: native changes (permissions, entitlements, plist keys) are invisible in review while ios/ and android/ are generated', fix: `Rerun this script with --write${variant ? ` --variant ${variant}` : ''}, read the file, and commit it.` });
    return report.finish({ checked: 1, unit: 'snapshots' });
  }
  const text = readFileSync(snapshotPath, 'utf8');
  let saved;
  try {
    saved = JSON.parse(text);
  } catch (error) {
    report.problem({ file: snapshotRel, line: 1, rule: 'native-snapshot', message: `the snapshot is not valid JSON (${error.message.split('\n')[0]})`, fix: 'Regenerate it with --write and review the result.' });
    return report.finish({ checked: 1, unit: 'snapshots' });
  }
  if ((saved.variant ?? null) !== variant) {
    report.problem({ file: snapshotRel, line: lineOf(text, '"variant"'), rule: 'native-snapshot', message: `the snapshot was written for ${JSON.stringify(saved.variant ?? null)}, this run introspects ${JSON.stringify(variant)}`, fix: `Pass --variant ${saved.variant ?? '<name>'}, or regenerate the snapshot for ${variant} with --write.` });
    return report.finish({ checked: 1, unit: 'snapshots' });
  }
  const differences = diff(stripMeta(saved), stripMeta(current));
  for (const entry of differences.slice(0, 40)) {
    report.problem({ file: snapshotRel, line: lineOfPath(text, entry.path), rule: 'native-drift', message: `${entry.path}: ${entry.change}`, fix: 'If the change is intended (a new plugin, option or package), rerun with --write and commit the snapshot with it; otherwise find the plugin or package that caused it (npx expo config --type introspect) and fix the config.' });
  }
  if (differences.length > 40) report.note(`note: ${differences.length - 40} more differences not shown`);
  return report.finish({ checked: 1, unit: 'snapshots' });
}

function findAppDir(root) {
  if (CONFIGS.some((name) => isFile(join(root, name)))) return '.';
  const apps = readWorkspaces(root).filter((ws) => CONFIGS.some((name) => isFile(join(root, ws.dir, name))));
  if (apps.length === 1) return apps[0].dir;
  if (apps.length > 1) throw new UsageError(`${apps.length} workspaces hold an app config (${apps.map((ws) => ws.dir).join(', ')})`, 'Pass the app with --app-dir <dir>, once per app.');
  return '.';
}

function readFrom(root, file) {
  const path = resolve(root, file);
  if (!isFile(path)) throw new UsageError(`--from ${file} does not exist`, 'Save one first: npx expo config --type introspect --json > <file>');
  return readJsonFile(path, file);
}

function expoCli(appDir) {
  let dir = appDir;
  for (let depth = 0; depth < 4; depth += 1) {
    const cli = join(dir, 'node_modules', 'expo', 'bin', 'cli');
    if (isFile(cli)) return cli;
    dir = dirname(dir);
  }
  return null;
}

/** Formats the written snapshot with the repo's own Prettier, so format:check stays green. */
function formatWithPrettier(root, appDir, file) {
  for (const base of [appDir, root]) {
    const bin = join(base, 'node_modules', 'prettier', 'bin', 'prettier.cjs');
    if (!isFile(bin)) continue;
    const result = spawnSync(process.execPath, [bin, '--write', '--log-level', 'warn', file], { cwd: base, encoding: 'utf8', timeout: 60000 });
    return result.status === 0;
  }
  return false;
}

function introspect(appDir, variant, envPairs) {
  const cli = expoCli(appDir);
  if (cli === null || !isDir(join(dirname(dirname(dirname(cli))), '@expo', 'config-plugins'))) {
    throw new UsageError('Expo is not installed here, so the native config cannot be introspected', 'Install the dependencies (npm ci), or pass --from <file> with the output of npx expo config --type introspect --json.');
  }
  const env = { ...process.env };
  for (const name of STRIPPED_ENV) delete env[name];
  if (variant !== null) Object.assign(env, { APP_VARIANT: variant, EXPO_PUBLIC_APP_VARIANT: variant });
  for (const pair of envPairs) {
    const at = pair.indexOf('=');
    if (at <= 0) throw new UsageError(`--env ${pair} is not KEY=VALUE`, 'Pass --env NAME=value, once per variable.');
    env[pair.slice(0, at)] = pair.slice(at + 1);
  }
  const result = spawnSync(process.execPath, [cli, 'config', '--type', 'introspect', '--json'], { cwd: appDir, env, encoding: 'utf8', timeout: 180000, maxBuffer: 64 * 1024 * 1024 });
  if (result.status !== 0) {
    const detail = `${result.stderr ?? ''}`.trim().split('\n').find((line) => line.trim() !== '') ?? `exit ${result.status}`;
    throw new UsageError(`npx expo config --type introspect failed: ${detail}`, 'Run it by hand to see the full error (check-native-generation.mjs explains most config errors), fix the config, rerun.');
  }
  const start = result.stdout.indexOf('{');
  return JSON.parse(result.stdout.slice(start));
}

// ---------------------------------------------------------------------------------------------
// Normalization: a stable, readable picture of the native surface
// ---------------------------------------------------------------------------------------------

function sortDeep(value) {
  if (Array.isArray(value)) return value.map(sortDeep);
  if (value === null || typeof value !== 'object') return value;
  return Object.fromEntries(Object.keys(value).sort().map((key) => [key, sortDeep(value[key])]));
}

const attrs = (node) => (node && typeof node === 'object' && node.$ ? node.$ : {});
const name = (node) => attrs(node)['android:name'] ?? '';
const short = (value) => String(value).replace(/^android\.(permission|intent\.action|intent\.category)\./, '');

function describeAttrs(node, skip = ['android:name']) {
  return Object.entries(attrs(node)).filter(([key]) => !skip.includes(key)).map(([key, value]) => `${key.replace(/^android:/, '')}=${value}`).sort().join(' ');
}

function describeIntent(intent) {
  const parts = [];
  for (const action of intent.action ?? []) parts.push(`action=${short(name(action))}`);
  for (const category of intent.category ?? []) parts.push(`category=${short(name(category))}`);
  for (const data of intent.data ?? []) parts.push(`data(${describeAttrs(data, [])})`);
  const own = describeAttrs(intent, []);
  return [own, ...parts].filter(Boolean).join(' ');
}

function permissionLines(manifest) {
  const out = [];
  for (const key of ['uses-permission', 'uses-permission-sdk-23']) {
    for (const node of manifest[key] ?? []) {
      const extra = describeAttrs(node);
      out.push(`${name(node)}${key === 'uses-permission-sdk-23' ? ' (sdk-23)' : ''}${extra ? ` ${extra}` : ''}`);
    }
  }
  return [...new Set(out)].sort();
}

function queryLines(manifest) {
  const out = [];
  for (const query of manifest.queries ?? []) {
    for (const pkg of query.package ?? []) out.push(`package ${name(pkg)}`);
    for (const intent of query.intent ?? []) out.push(`intent ${describeIntent(intent)}`);
    for (const provider of query.provider ?? []) out.push(`provider ${attrs(provider)['android:authorities'] ?? ''}`);
  }
  return [...new Set(out)].sort();
}

function components(application) {
  const out = {};
  for (const kind of ['activity', 'activity-alias', 'service', 'receiver', 'provider']) {
    for (const node of application[kind] ?? []) {
      out[`${kind} ${name(node)}`] = {
        attributes: describeAttrs(node),
        intentFilters: (node['intent-filter'] ?? []).map(describeIntent).sort(),
      };
    }
  }
  return out;
}

function normalizeAndroid(results) {
  const manifest = results?.manifest?.manifest ?? {};
  const application = (manifest.application ?? [])[0] ?? {};
  const metaData = {};
  for (const node of application['meta-data'] ?? []) metaData[name(node)] = attrs(node)['android:value'] ?? attrs(node)['android:resource'] ?? '';
  const gradle = {};
  for (const entry of results?.gradleProperties ?? []) if (entry.type === 'property') gradle[entry.key] = entry.value;
  const strings = {};
  for (const node of results?.strings?.resources?.string ?? []) strings[attrs(node).name ?? ''] = node._ ?? '';
  return {
    permissions: permissionLines(manifest),
    features: (manifest['uses-feature'] ?? []).map((node) => `${name(node)} ${describeAttrs(node)}`.trim()).sort(),
    queries: queryLines(manifest),
    application: describeAttrs(application, []),
    components: components(application),
    metaData,
    gradleProperties: gradle,
    strings,
  };
}

function normalizeIos(results) {
  const infoPlist = { ...(results?.infoPlist ?? {}) };
  for (const key of VERSION_KEYS) delete infoPlist[key];
  return {
    infoPlist,
    entitlements: results?.entitlements ?? {},
    expoPlist: results?.expoPlist ?? {},
    podfileProperties: results?.podfileProperties ?? {},
  };
}

function normalize(introspection, variant) {
  const results = introspection?._internal?.modResults;
  if (!results || typeof results !== 'object') {
    throw new UsageError('the introspection has no _internal.modResults', 'Produce it with npx expo config --type introspect --json (not --type public).');
  }
  return { $comment: COMMENT, variant, ios: sortDeep(normalizeIos(results.ios)), android: sortDeep(normalizeAndroid(results.android)) };
}

function stripMeta(snapshot) {
  const { $comment: _comment, variant: _variant, ...rest } = snapshot;
  return rest;
}

// ---------------------------------------------------------------------------------------------
// Differences
// ---------------------------------------------------------------------------------------------

function show(value) {
  const text = JSON.stringify(value);
  return text.length > 120 ? `${text.slice(0, 117)}...` : text;
}

/** Leaf differences: [{ path, change }]; arrays of strings compare as sets (added/removed items). */
function diff(before, after, path = '') {
  if (JSON.stringify(before) === JSON.stringify(after)) return [];
  const isList = (value) => Array.isArray(value) && value.every((item) => typeof item === 'string');
  if (isList(before) && isList(after)) {
    return [
      ...after.filter((item) => !before.includes(item)).map((item) => ({ path, change: `added ${show(item)}` })),
      ...before.filter((item) => !after.includes(item)).map((item) => ({ path, change: `removed ${show(item)}` })),
    ];
  }
  const isObject = (value) => value !== null && typeof value === 'object' && !Array.isArray(value);
  if (isObject(before) && isObject(after)) {
    const keys = [...new Set([...Object.keys(before), ...Object.keys(after)])].sort();
    return keys.flatMap((key) => {
      const sub = path ? `${path}.${key}` : key;
      if (!(key in before)) return [{ path: sub, change: `added ${show(after[key])}` }];
      if (!(key in after)) return [{ path: sub, change: `removed (was ${show(before[key])})` }];
      return diff(before[key], after[key], sub);
    });
  }
  return [{ path: path || '(snapshot)', change: `changed from ${show(before)} to ${show(after)}` }];
}

/** The line of the deepest key of a dotted path that the snapshot text holds (an added key points at its parent). */
function lineOfPath(text, path) {
  const keys = path.split('.');
  for (let index = keys.length - 1; index >= 0; index -= 1) {
    if (text.includes(`"${keys[index]}"`)) return lineOf(text, `"${keys[index]}"`);
  }
  return 1;
}

function lineOf(text, needle) {
  const at = text.indexOf(needle);
  return at === -1 ? 1 : text.slice(0, at).split('\n').length;
}

run(main);
